import React from "react";
import { C, BAD } from "./ui.jsx";

/* ════════════════════════════════════════════════════════════════
   ПОЛЕ В РАМКЕ

   Обычная подпись над полем (S.lbl) стоит отдельной строкой и «плавает»:
   когда полей несколько, глазу не видно, где кончается одно и начинается
   следующее, — подпись одинаково близка к полю сверху и к полю снизу. В
   бумажных бланках эту задачу решили давно: поле обводят рамкой, а название
   вписывают в разрыв верхней линии — на середине высоты букв. Тогда подпись
   принадлежит своему полю явно, а не по соседству.

   Делается это НЕ хитрой вёрсткой с абсолютным блоком и белой подложкой
   (подложка выдаёт себя на любом фоне, кроме ровного, и ломается при
   переносе подписи на две строки), а парой fieldset + legend: браузер сам
   разрывает рамку ровно под ширину legend и сам центрирует её на линии.
   Это тот редкий случай, когда «старый» элемент делает именно то, что
   нужно, и надёжнее всего, что можно собрать поверх него.

   Доступность: fieldset с legend читалки объявляют группой с названием,
   и человек слышит «Телефон», входя в поле. aria-label ставим тем же
   текстом — по нему поле находят и тесты, и голосовое управление.
   ════════════════════════════════════════════════════════════════ */

export default function FramedField({ label, children, required, style }) {
  return (
    <fieldset aria-label={label}
      style={{
        border: `1px solid ${C.line}`, borderRadius: 6,
        // Сверху отступ меньше: часть места уже забрала legend, врезанная в
        // линию. Снизу — больше, иначе поле липнет к рамке.
        padding: "6px 8px 8px", margin: "0 0 8px",
        // minWidth: 0 — у fieldset своя ширина по содержимому, и без этого
        // он отказывается ужиматься внутри flex/grid на телефоне.
        minWidth: 0, ...style,
      }}>
      <legend style={{ fontSize: 11, color: C.muted, padding: "0 4px" }}>
        {label}
        {/* Звёздочка — только знак, смысл несёт проверка при отправке.
            Для читалки она скрыта: «Телефон звёздочка» слушать незачем. */}
        {required && <span aria-hidden="true" style={{ color: BAD }}> *</span>}
      </legend>
      {children}
    </fieldset>);
}

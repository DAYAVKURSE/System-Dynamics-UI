/* ════════════════════════════════════════════════════════════════
   АКТИВ, ЕГО ВОРКЕРЫ, ЕГО ФУНКЦИИ И ЕГО РЕСУРСЫ

   Строение задано владельцем и здесь воспроизведено буквально:

   Актив
     ├── воркеры: исполнители и проверяющие — люди актива;
     ├── функции: то, что эти воркеры выполняют;
     └── ресурсы: то, что функции при этом потребляют и передают.

   Воркеры принадлежат АКТИВУ, а не функции: сначала у актива есть люди,
   потом они разбираются по его функциям. Поэтому исполнителя функции
   можно выбрать только из воркеров её актива — иначе «люди актива»
   превратились бы в подпись под тем, что задано в другом месте.

   ─── как устроена запись функции ───

   Функция живёт внутри актива (`e`) и связана с ресурсами двумя списками:

   · takes — что берёт: [{trait, lo, hi}]
   · gives — что выдаёт: [{trait, lo, hi, to}]

   Функция может только взять и дать: взять несколько ресурсов и выдать
   несколько других. Третьего действия у неё нет. Но выданное она может
   передать в другой актив — это `to` у выхода: пусто значит «остаётся в
   своём активе», иначе там стоит актив-получатель.

   Почему передача — поле выхода, а не отдельный список стрелок. Передаётся
   именно то, что функция выдала: список рядом означал бы, что выдать можно
   одно, а передать другое, и два места разошлись бы в первый же день.

   ─── про диапазоны ───

   Сколько ресурса функция возьмёт и сколько выдаст — это не число, а
   вилка `lo`..`hi`. Сначала она закладывается как гипотеза, потом
   уточняется на реальных выполнениях: по ним считается среднее
   арифметическое, и оно показывается рядом с планом.

   Одно точное число здесь было бы обещанием, которого никто не давал, а
   план, выданный за факт, — обманом. Поэтому и цвета разные: план
   жёлтый, факт зелёный.

   ─── про время ───

   `dur` — длительность ОДНОГО выполнения функции: «за какое время
   дизайнер сделает дизайн страницы». Не производительность за период.
   Время у функции одно: выполнение либо случилось целиком, либо нет, и
   раздавать разным её выходам разные сроки не за что.

   `every` — как часто функция повторяется: «раз в неделю», «раз в месяц».
   Пусто значит «непрерывно»: следующее выполнение начинается сразу за
   предыдущим, и всё упирается только в `dur`. Одно другого не заменяет:
   работа может занимать час, но делаться раз в месяц, и наоборот —
   занимать неделю и идти без передышки.
   ════════════════════════════════════════════════════════════════ */

/** Единицы длительности. Значение — сколько в них часов. */
export const DUR_UNITS = { ч: 1, дн: 24, нед: 168, мес: 730 };
export const DUR_DEFAULT = "дн";

let seq = 0;
const nextId = (prefix) => {
  seq += 1;
  return `${prefix}${Date.now().toString(36)}${seq.toString(36)}`;
};

const num = (v) => Number(v) || 0;

/**
 * Вход или выход функции: ресурс и вилка «сколько».
 *
 * Новый порт заводится вилкой 1..1 — не нулём: ноль означал бы «ресурс
 * есть в рецепте, но не расходуется», а это не то, что человек имел в
 * виду, нажимая «+ берёт».
 */
export const newPort = (trait = "", lo = 1, hi = 1, group = null) => {
  const id = nextId("p");
  return { id, trait, lo: num(lo), hi: num(hi), group: group || id };
};

/* ─────── «и» между группами, «или» внутри группы ───────

   Вход функции — не плоский список. «Нужен А и Б, но вместо Б годится В»
   плоским списком не сказать: он умеет только «и».

   Поэтому у входа есть `group`. Входы с одной группой — это варианты одного
   и того же требования, между ними «или»; разные группы соединены «и».
   Новый вход заводится в собственной группе — то есть всё, что собрано до
   сих пор, остаётся ровно тем же «и».

   Количество у каждого варианта и есть курс обмена: «2 А» в одной группе с
   «3 В» значит, что три В заменяют два А. Отдельного поля для курса нет —
   оно спрашивало бы то, что уже сказано двумя числами. */
export const groupsOf = (ports = []) => {
  const by = new Map();
  ports.forEach((p) => {
    const g = p.group || p.id;
    if (!by.has(g)) by.set(g, []);
    by.get(g).push(p);
  });
  return [...by.values()];
};

/** Сколько у функции разных требований: групп, а не входов. */
export const groupCount = (ports = []) => groupsOf(ports).length;

/**
 * Выход функции — такой же порт, как и вход.
 *
 * Получателя у выхода нет и быть не может: ресурс уже принадлежит своему
 * активу, и функция выдаёт его туда, где он есть. Отдельное поле «передаёт
 * в» спрашивало бы то, что уже сказано выбором ресурса, — и разъехалось бы
 * с ним в первый же день, когда одно поправили, а другое забыли.
 */
export const newGive = (trait = "", lo = 1, hi = 1) => newPort(trait, lo, hi);

/**
 * Чем функция выполняется: людьми или само собой.
 *
 * «Задача» — работу делают люди: у неё есть постановщик, исполнитель и
 * проверяющий, и из неё берутся задачи на доске. «Фактор» — то, что
 * происходит без человека: сезон, износ, реклама, которая крутится сама.
 * Ресурсы фактор меняет так же, как задача, но спрашивать с него некого —
 * и назначать на него людей значило бы поставить кого-то отвечать за
 * погоду.
 */
export const FUNC_KINDS = [
  { id: "task", name: "Задача" },
  { id: "factor", name: "Фактор" },
];
export const funcKind = (f) => (f?.kind === "factor" ? "factor" : "task");
export const isFactor = (f) => funcKind(f) === "factor";

/** Новая функция внутри актива. Пока не сказано иное — это работа людей. */
export const newFunc = (e, name = "новая функция") => ({
  id: nextId("f"),
  e,
  name,
  kind: "task",
  factor: "",
  takes: [],
  gives: [],
  dur: 1,
  // Верхняя граница времени. Новая функция заводится точным сроком:
  // вилка «от 1 до 1» — это то же самое число, только сказанное дважды.
  durHi: 1,
  durUnit: DUR_DEFAULT,
  // Пусто — «сразу»: следующая попытка начинается за предыдущей.
  every: 0,
  everyHi: 0,
  everyUnit: DUR_DEFAULT,
  setters: [],
  owners: [],
  reviewers: [],
  x: 0,
  y: 0,
});

/* ─────── сколько времени уходит на одно выполнение ───────

   Тоже вилка, как и количества: «от 2 до 4 часов». Одно число здесь было
   бы обещанием, которого никто не давал, — работа редко занимает ровно
   столько, сколько задумано. Стороны разводятся так же, как у ресурсов:
   осторожная оценка берёт верхнюю границу времени, щедрая — нижнюю.

   Когда время известно точно, границы просто равны — для этого в форме
   стоит галочка «одинаковое». */
export const hoursRange = ({ dur, durHi, durUnit } = {}) => {
  const k = DUR_UNITS[durUnit] ?? 1;
  const lo = num(dur) * k;
  const hi = durHi == null ? lo : num(durHi) * k;
  return hi < lo ? { lo: hi, hi: lo } : { lo, hi };
};

/**
 * Длительность в часах — общая мера для сравнения и усреднения.
 *
 * `side` выбирает границу: "lo" — быстрая работа, "hi" — долгая. Без
 * стороны берётся середина вилки: там, где нужна одна цифра (подпись,
 * срок задачи), середина честнее любого края.
 */
export const hoursOf = (f = {}, side) => {
  const { lo, hi } = hoursRange(f);
  if (side === "lo") return lo;
  if (side === "hi") return hi;
  return (lo + hi) / 2;
};

/** Задано ли время одним числом, а не вилкой. */
export const sameHours = (f = {}) => {
  const { lo, hi } = hoursRange(f);
  return lo === hi;
};

/* ─────── через сколько будет следующая попытка ───────

   Тоже вилка, и тоже не длительность: работа может занимать час, а
   следующая попытка случаться через неделю. Ноль значит «сразу»: следующая
   попытка начинается, как только закончилась предыдущая, и всё упирается
   только в саму работу.

   Слово «попытка», а не «повторение», — потому что попытка может и не
   удаться: у фактора есть вероятность, и неудачная попытка просто ничего
   не делает, дожидаясь следующей. */
export const everyRange = ({ every, everyHi, everyUnit } = {}) => {
  const k = DUR_UNITS[everyUnit] ?? 1;
  const lo = num(every) * k;
  const hi = everyHi == null ? lo : num(everyHi) * k;
  return hi < lo ? { lo: hi, hi: lo } : { lo, hi };
};

/**
 * Через сколько часов следующая попытка. Ноль — «сразу».
 *
 * `side` выбирает границу: щедрой оценке достаётся частая попытка (нижняя
 * граница), осторожной — редкая. Без стороны — середина вилки.
 */
export const everyOf = (f = {}, side) => {
  const { lo, hi } = everyRange(f);
  if (side === "hi") return lo;
  if (side === "lo") return hi;
  return (lo + hi) / 2;
};

/** Задан ли срок попытки одним числом, а не вилкой. */
export const sameEvery = (f = {}) => {
  const { lo, hi } = everyRange(f);
  return lo === hi;
};

/* ─────── вероятность, что попытка удастся ───────

   Свойство САМОГО ФАКТОРА, а не функции. Сезон бывает удачным с одной и
   той же вероятностью, сколько бы функций от него ни зависело; спрашивать
   её у каждой функции значило бы задавать один вопрос по нескольку раз и
   получать разные ответы.

   У задачи вероятности нет вовсе: работу делает человек, и «выйдет с
   вероятностью 60%» про неё сказать нельзя — либо назначили, либо нет. */
export const CHANCE_MAX = 100;
const clampChance = (v) => Math.max(0, Math.min(CHANCE_MAX, num(v)));
export const chanceOf = (f = {}, factors = []) => {
  if (!isFactor(f)) return CHANCE_MAX;
  const x = factors.find((y) => y.id === f.factor);
  return x?.chance == null ? CHANCE_MAX : clampChance(x.chance);
};

/** По-человечески: «сразу» или «через 2 нед», вилкой — «через 1–2 нед». */
export const everyText = (f) => {
  const { lo, hi } = everyRange(f);
  if (lo <= 0 && hi <= 0) return "сразу";
  return sameEvery(f)
    ? `через ${nmDur(f.every)} ${f.everyUnit}`
    : `через ${nmDur(f.every)}–${nmDur(f.everyHi)} ${f.everyUnit}`;
};
const nmDur = (v) => (Math.round(num(v) * 100) / 100);

/**
 * Приведение чужой записи к нынешней.
 *
 * Достраиваем недостающее — не более того. Записи прежних версий (стрелки
 * между элементами, `qty` вместо вилки, сроки и люди на каждом выходе)
 * здесь НЕ переносятся: владелец сказал прямо — прежние модели работать не
 * должны. Молчаливый перенос был бы хуже отказа: получилась бы модель,
 * которую никто не собирал, и разбираться в ней пришлось бы дольше, чем
 * собрать заново.
 */
export const normalizeFunc = (f = {}) => {
  // Вход и выход устроены одинаково. Прежнее поле получателя `to` не
  // читается и не сохраняется: получатель — это актив самого ресурса.
  /* Вход и выход устроены одинаково, кроме одного: «или» бывает только у
     входа. У выхода группа всегда своя — функция выдаёт то, что выдаёт, и
     «выдаст А или Б» без правила, что именно, было бы не моделью, а
     монеткой. Поэтому поле есть, но выразить им у выхода нечего. */
  const port = (p = {}, grouped = false) => {
    const id = p.id ?? nextId("p");
    return {
      id,
      trait: p.trait ?? "",
      lo: num(p.lo),
      hi: num(p.hi),
      group: (grouped && p.group) || id,
    };
  };
  const unit = (u) => (DUR_UNITS[u] ? u : DUR_DEFAULT);
  return {
    ...f,
    e: f.e ?? null,
    name: f.name ?? "",
    kind: funcKind(f),
    factor: f.factor ?? "",
    takes: Array.isArray(f.takes) ? f.takes.map((p) => port(p, true)) : [],
    gives: Array.isArray(f.gives) ? f.gives.map((p) => port(p)) : [],
    dur: num(f.dur),
    // Записи без верхней границы — это точный срок, а не сломанная вилка.
    durHi: f.durHi == null ? num(f.dur) : num(f.durHi),
    durUnit: unit(f.durUnit),
    every: num(f.every),
    everyHi: f.everyHi == null ? num(f.every) : num(f.everyHi),
    everyUnit: unit(f.everyUnit),
    ...Object.fromEntries(WORKER_KINDS.map((k) => [k.id,
      [...new Set(Array.isArray(f[k.id]) ? f[k.id] : [])]])),
    x: num(f.x),
    y: num(f.y),
  };
};

export const normalizeFuncs = (list) =>
  (Array.isArray(list) ? list.map(normalizeFunc) : []);

/** Обратно в удобные единицы: 36 часов — это «1.5 дн», а не «36 ч». */
export function fromHours(h) {
  const n = num(h);
  const unit = ["мес", "нед", "дн", "ч"].find((u) => n >= DUR_UNITS[u]) || "ч";
  return { dur: Math.round((n / DUR_UNITS[unit]) * 10) / 10, durUnit: unit };
}

/**
 * Среднее арифметическое по фактическим выполнениям.
 *
 * Считается только по состоявшимся: незакрытое выполнение ничего не
 * измеряет, а взятое в расчёт занижало бы среднее ровно тогда, когда
 * работа идёт.
 */
export const avgOf = (list = []) => {
  const done = list.map(Number).filter((v) => Number.isFinite(v) && v > 0);
  if (!done.length) return null;
  return done.reduce((s, v) => s + v, 0) / done.length;
};

/**
 * Выполнение функции — это `{hours, takes:{ресурс:сколько}, gives:{…}}`.
 * Отсюда и берётся «в реальных показывается среднеарифметическое».
 */
export const runHours = (runs = []) => avgOf(runs.map((r) => r?.hours));
export const runQty = (runs = [], kind, trait) =>
  avgOf(runs.map((r) => r?.[kind]?.[trait]));

/** Вилка по-человечески: «от 3 до 5», «ровно 4», «от 3». */
export const rangeText = (p) => {
  const lo = num(p?.lo);
  const hi = num(p?.hi);
  if (!lo && !hi) return "сколько — не задано";
  if (lo === hi) return `ровно ${lo}`;
  if (!hi) return `от ${lo}`;
  if (!lo) return `до ${hi}`;
  return `от ${lo} до ${hi}`;
};

/**
 * Годна ли вилка.
 *
 * Перевёрнутая — не мелочь: «от 5 до 3» молча считалась бы как попало, а
 * человек был бы уверен, что задал границы. Пустая тоже не годится:
 * ресурс в рецепте без количества ничего не переносит.
 */
export const okRange = (p) => {
  const lo = num(p?.lo);
  const hi = num(p?.hi);
  return hi >= lo && (lo > 0 || hi > 0);
};

/* ════════════════════════════════════════════════════════════════
   ВОРКЕРЫ АКТИВА

   У актива три вида людей — это его воркеры:

   · постановщики (`setters`) — те, кто ставит задачу и пишет, что в ней
     сделать;
   · исполнители (`owners`) — те, кто её выполняет;
   · проверяющие (`reviewers`) — те, кто принимает отчёт.

   Все три обязательны: без постановщика непонятно, кто описал работу; без
   исполнителя её некому делать; без проверяющего некому принять, а значит
   сделанное не попадёт в расчёт.

   Функции выполняют они же, поэтому назначить на функцию можно только
   воркера её актива.
   ════════════════════════════════════════════════════════════════ */

const ids = (v) => (Array.isArray(v) ? [...new Set(v.filter((x) => x != null))] : []);

/** Три вида воркеров — в одном месте, чтобы нигде не забыть третий. */
export const WORKER_KINDS = [
  { id: "setters", one: "постановщик", many: "постановщики", task: "постановщик" },
  { id: "owners", one: "исполнитель", many: "исполнители", task: "исполнитель" },
  { id: "reviewers", one: "проверяющий", many: "проверяющие", task: "проверяющий" },
];

/** Достраивает актив до нынешней записи: у него есть воркеры. */
export const normalizeAsset = (e = {}) => ({
  ...e,
  ...Object.fromEntries(WORKER_KINDS.map((k) => [k.id, ids(e[k.id])])),
});

export const normalizeAssets = (list) =>
  (Array.isArray(list) ? list.map(normalizeAsset) : []);

/** Воркеры актива: постановщики, исполнители и проверяющие. */
export const workersOf = (entities = [], id) => {
  const e = entities.find((x) => x.id === id);
  return Object.fromEntries(WORKER_KINDS.map((k) => [k.id, ids(e?.[k.id])]));
};

/**
 * Сколько у актива воркеров — ЛЮДЕЙ, а не назначений.
 *
 * Один человек может быть и постановщиком, и исполнителем, и проверяющим
 * сразу — в маленькой команде это норма, а не ошибка. Складывать длины
 * трёх списков значило бы посчитать одного человека трижды и написать
 * «3 воркера» там, где работает один. Число на вкладке отвечает на вопрос
 * «сколько нас», а не «сколько галочек проставлено».
 */
export const countWorkers = (workers = {}) => new Set(
  WORKER_KINDS.flatMap((k) => ids(workers[k.id]).map(String)),
).size;

/**
 * Чего не хватает, чтобы функцию можно было выполнить прямо сейчас.
 *
 * Возвращает список нехваток: по одной на каждое требование, которое нечем
 * закрыть. Внутри требования достаточно ОДНОГО подходящего варианта — на то
 * оно и «или»; не хватает, только если не хватает всех сразу.
 *
 * Считается по верхней границе вилки — по тому, сколько может понадобиться.
 * Взяться за работу, зная, что ресурса хватит лишь в удачном случае, —
 * значит заранее согласиться встать на полпути.
 */
export function shortage(f, traits = []) {
  if (!f) return [];
  const have = (id) => num(traits.find((t) => t.id === id)?.have);
  const name = (id) => traits.find((t) => t.id === id)?.l || "(ресурс удалён)";
  return groupsOf(f.takes || [])
    .map((g) => {
      const ok = g.some((p) => have(p.trait) >= num(p.hi || p.lo));
      if (ok) return null;
      // Показываем тот вариант, которого не хватает меньше всего: до него
      // ближе всего, и именно он подскажет, чего добирать.
      const best = g.reduce((a, p) => {
        const gap = num(p.hi || p.lo) - have(p.trait);
        return a && a.gap <= gap ? a : { p, gap };
      }, null);
      return best && {
        trait: best.p.trait,
        name: name(best.p.trait),
        need: num(best.p.hi || best.p.lo),
        have: have(best.p.trait),
        alts: g.length,
      };
    })
    .filter(Boolean);
}

/** Хватает ли ресурсов, чтобы взяться за функцию прямо сейчас. */
export const canRun = (f, traits = []) => shortage(f, traits).length === 0;

/**
 * Людей, переставших быть воркерами актива, убираем и с его функций.
 *
 * Иначе исполнитель остался бы назначенным, не значась в активе: задача
 * висела бы на человеке, которого в этом активе уже нет.
 */
export const pruneWorkers = (funcs = [], id, workers) => {
  const keep = (k) => new Set(ids(workers?.[k]));
  return funcs.map((f) => (f.e !== id ? f : {
    ...f,
    ...Object.fromEntries(WORKER_KINDS.map((k) => [k.id,
      (f[k.id] || []).filter((p) => keep(k.id).has(p))])),
  }));
};


/* ════════════════════════════════════════════════════════════════
   ФУНКЦИОНАЛЬНЫЕ ЭЛЕМЕНТЫ

   Ресурс — это то, что есть. Функциональный элемент — то, что его
   преобразует: берёт одни ресурсы и выдаёт другие, и на это уходит время.
   До сих пор преобразование жило прямо в стрелке между ресурсами, и
   поэтому его нельзя было ни поручить человеку, ни измерить: у стрелки
   нет ни ответственного, ни длительности, ни истории выполнения.

   Почему ОТДЕЛЬНЫЙ массив, а не ещё один вид ресурса. Ресурсы в этой
   модели — числа: они складываются, участвуют в целях, в условиях, в
   формулах, в подсказках, в прогнозе. Положив элемент к ним, мы получили
   бы «цель по функциональному элементу» и «долю от функционального
   элемента» в семи списках сразу. Элемент — не число, и путать их нельзя.

   ─── как устроена запись ───

   Элемент живёт внутри актива (`e`) и связан с ресурсами двумя списками:

   · takes — что берёт: [{trait, qty}]
   · gives — что выдаёт, и это ФУНКЦИИ элемента: у каждой свои
     длительность, ответственные и проверяющие. Владелец сказал прямо:
     «у каждого функционального элемента для разных функций, которыми они
     выдают ресурс, должны быть проверяющие», — значит функция это выход,
     а не элемент целиком.

   ─── про время ───

   `dur` — длительность ОДНОГО выполнения: «за какое время дизайнер
   сделает дизайн страницы». Не производительность за период. Из неё
   считается и срок задачи, и то, сколько выполнений помещается в шаг
   прогноза; а рядом копится факт — сколько вышло на самом деле.

   План показывается жёлтым, пока не выполнено ни одного цикла, и
   сменяется зелёным средним, когда циклы появились: пока факта нет,
   жёлтое число — обещание, а не измерение, и выдавать одно за другое
   нельзя.
   ════════════════════════════════════════════════════════════════ */

/** Единицы длительности. Значение — сколько в них часов. */
export const DUR_UNITS = { ч: 1, дн: 24, нед: 168, мес: 730 };
export const DUR_DEFAULT = "дн";

let seq = 0;
const nextId = (prefix) => {
  seq += 1;
  return `${prefix}${Date.now().toString(36)}${seq.toString(36)}`;
};

/** Одна функция элемента: что выдаёт, за сколько, кто делает и проверяет. */
export const newGive = (trait = "", qty = 1) => ({
  id: nextId("g"),
  trait,
  qty,
  dur: 1,
  durUnit: DUR_DEFAULT,
  owners: [],
  reviewers: [],
});

/** Новый функциональный элемент внутри актива. */
export const newFunc = (e, name = "новая функция") => ({
  id: nextId("f"),
  e,
  name,
  takes: [],
  gives: [],
  x: 0,
  y: 0,
});

/**
 * Приведение к нынешней записи.
 *
 * Сценарии и модели, сохранённые до появления элементов, поля funcs не
 * знают вовсе — там будет undefined, и это нормально. А вот запись,
 * пришедшую из чужого JSON, надо достроить: без списков takes/gives
 * редактор упадёт на первом же map, и человек увидит белый экран вместо
 * объяснения.
 */
export const normalizeFunc = (f) => ({
  ...f,
  e: f.e ?? null,
  name: f.name ?? "",
  takes: Array.isArray(f.takes) ? f.takes.map((t) => ({ trait: t.trait ?? "", qty: Number(t.qty) || 0 })) : [],
  gives: Array.isArray(f.gives) ? f.gives.map((g) => ({
    id: g.id ?? nextId("g"),
    trait: g.trait ?? "",
    qty: Number(g.qty) || 0,
    dur: Number(g.dur) || 0,
    durUnit: DUR_UNITS[g.durUnit] ? g.durUnit : DUR_DEFAULT,
    owners: Array.isArray(g.owners) ? g.owners : [],
    reviewers: Array.isArray(g.reviewers) ? g.reviewers : [],
  })) : [],
  x: Number(f.x) || 0,
  y: Number(f.y) || 0,
});

export const normalizeFuncs = (list) =>
  (Array.isArray(list) ? list.map(normalizeFunc) : []);

/** Длительность функции в часах — общая мера для сравнения и усреднения. */
export const hoursOf = ({ dur, durUnit } = {}) =>
  (Number(dur) || 0) * (DUR_UNITS[durUnit] ?? 1);

/** Обратно в удобные единицы: 36 часов — это «1.5 дн», а не «36 ч». */
export const fromHours = (h) => {
  const n = Number(h) || 0;
  const unit = ["мес", "нед", "дн", "ч"].find((u) => n >= DUR_UNITS[u]) || "ч";
  return { dur: Math.round((n / DUR_UNITS[unit]) * 10) / 10, durUnit: unit };
};

/**
 * Сколько выполнений функции помещается в один шаг прогноза.
 *
 * Шаг модели — месяц. Цикл короче месяца повторяется несколько раз; цикл
 * длиннее месяца выдаёт долю — иначе результат, на который ушло полгода,
 * появлялся бы разом и модель врала бы о сроках.
 */
export const cyclesPerMonth = (give) => {
  const h = hoursOf(give);
  return h > 0 ? DUR_UNITS["мес"] / h : 0;
};

/**
 * Среднее фактическое время цикла по выполненным задачам.
 *
 * Считается только по завершённым: незакрытая задача ничего не измеряет,
 * а взятая в расчёт занижала бы среднее ровно тогда, когда работа идёт.
 */
export const avgHours = (cycles = []) => {
  const done = cycles.filter((c) => Number(c) > 0);
  if (!done.length) return null;
  return done.reduce((s, c) => s + Number(c), 0) / done.length;
};

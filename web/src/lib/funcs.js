/* ════════════════════════════════════════════════════════════════
   АКТИВ, ЕГО ВОРКЕРЫ, ЕГО ФУНКЦИИ И ЕГО РЕСУРСЫ

   Строение задано владельцем и здесь воспроизведено буквально:

   Актив
     ├── воркеры: исполнители и проверяющие — люди актива;
     ├── функции: то, что эти воркеры выполняют;
     └── ресурсы: то, что функции при этом потребляют и передают.

   Воркеры принадлежат АКТИВУ, а не функции: сначала у актива есть люди,
   потом они разбираются по его функциям. Поэтому исполнителя функции
   можно выбрать только из воркеров её актива — иначе «люди актива»
   превратились бы в подпись под тем, что задано в другом месте.

   ─── как устроена запись функции ───

   Функция живёт внутри актива (`e`) и связана с ресурсами двумя списками:

   · takes — что берёт: [{trait, lo, hi}]
   · gives — что выдаёт: [{trait, lo, hi, to}]

   Функция может только взять и дать: взять несколько ресурсов и выдать
   несколько других. Третьего действия у неё нет. Но выданное она может
   передать в другой актив — это `to` у выхода: пусто значит «остаётся в
   своём активе», иначе там стоит актив-получатель.

   Почему передача — поле выхода, а не отдельный список стрелок. Передаётся
   именно то, что функция выдала: список рядом означал бы, что выдать можно
   одно, а передать другое, и два места разошлись бы в первый же день.

   ─── про диапазоны ───

   Сколько ресурса функция возьмёт и сколько выдаст — это не число, а
   вилка `lo`..`hi`. Сначала она закладывается как гипотеза, потом
   уточняется на реальных выполнениях: по ним считается среднее
   арифметическое, и оно показывается рядом с планом.

   Одно точное число здесь было бы обещанием, которого никто не давал, а
   план, выданный за факт, — обманом. Поэтому и цвета разные: план
   жёлтый, факт зелёный.

   ─── про время ───

   `dur` — длительность ОДНОГО выполнения функции: «за какое время
   дизайнер сделает дизайн страницы». Не производительность за период.
   Время у функции одно: выполнение либо случилось целиком, либо нет, и
   раздавать разным её выходам разные сроки не за что.

   `every` — как часто функция повторяется: «раз в неделю», «раз в месяц».
   Пусто значит «непрерывно»: следующее выполнение начинается сразу за
   предыдущим, и всё упирается только в `dur`. Одно другого не заменяет:
   работа может занимать час, но делаться раз в месяц, и наоборот —
   занимать неделю и идти без передышки.
   ════════════════════════════════════════════════════════════════ */

/** Единицы длительности. Значение — сколько в них часов. */
export const DUR_UNITS = { ч: 1, дн: 24, нед: 168, мес: 730 };
export const DUR_DEFAULT = "дн";

let seq = 0;
const nextId = (prefix) => {
  seq += 1;
  return `${prefix}${Date.now().toString(36)}${seq.toString(36)}`;
};

const num = (v) => Number(v) || 0;

/**
 * Вход или выход функции: ресурс и вилка «сколько».
 *
 * Новый порт заводится вилкой 1..1 — не нулём: ноль означал бы «ресурс
 * есть в рецепте, но не расходуется», а это не то, что человек имел в
 * виду, нажимая «+ берёт».
 */
export const newPort = (trait = "", lo = 1, hi = 1, group = null) => {
  const id = nextId("p");
  return { id, trait, lo: num(lo), hi: num(hi), group: group || id, spend: true };
};

/* ─────── «и» между группами, «или» внутри группы ───────

   Вход функции — не плоский список. «Нужен А и Б, но вместо Б годится В»
   плоским списком не сказать: он умеет только «и».

   Поэтому у входа есть `group`. Входы с одной группой — это варианты одного
   и того же требования, между ними «или»; разные группы соединены «и».
   Новый вход заводится в собственной группе — то есть всё, что собрано до
   сих пор, остаётся ровно тем же «и».

   Количество у каждого варианта и есть курс обмена: «2 А» в одной группе с
   «3 В» значит, что три В заменяют два А. Отдельного поля для курса нет —
   оно спрашивало бы то, что уже сказано двумя числами. */
export const groupsOf = (ports = []) => {
  const by = new Map();
  ports.forEach((p) => {
    const g = p.group || p.id;
    if (!by.has(g)) by.set(g, []);
    by.get(g).push(p);
  });
  return [...by.values()];
};

/** Сколько у функции разных требований: групп, а не входов. */
export const groupCount = (ports = []) => groupsOf(ports).length;

/* ─────── расходует вход или только обрабатывает ───────

   Взять ресурс можно двумя способами, и они разные.

   · РАСХОДУЕТ — взятое исчезает. Ткань, из которой сшили платье, больше
     ничья: ни эта функция, ни соседняя её уже не получат.
   · НЕ РАСХОДУЕТ — взятое остаётся на месте, но ЭТА функция его уже
     обработала. Заявку прочитали и оценили — заявка никуда не делась, её
     прочитает и другая функция; но второй раз оценивать ту же заявку
     незачем, работа по ней уже сделана.

   Прежде расходовалось всё и всегда, и получалось, что прочитанная заявка
   пропадала у всех остальных. Ограничение «второй раз не берём» относится
   к ОДНОЙ функции, а не ко всем сразу. */
export const portSpends = (p = {}) => p.spend !== false;

/**
 * Выход функции — такой же порт, как и вход.
 *
 * Получателя у выхода нет и быть не может: ресурс уже принадлежит своему
 * активу, и функция выдаёт его туда, где он есть. Отдельное поле «передаёт
 * в» спрашивало бы то, что уже сказано выбором ресурса, — и разъехалось бы
 * с ним в первый же день, когда одно поправили, а другое забыли.
 */
export const newGive = (trait = "", lo = 1, hi = 1) => newPort(trait, lo, hi);

/* ─── «вид» функции ───

   Прежде функция была либо задачей (её делают люди), либо фактором
   (случается сам, без людей). Владелец это снял: у любой функции есть
   постановщик, исполнитель и проверяющий, а факторы — не другой вид, а
   КОНВЕРСИЯ: сколько входа уходит на одну единицу выхода. Функция без
   факторов конвертирует 1:1; с факторами на 10% — берёт вдесятеро больше.
   Старая запись с `kind: "factor"` читается как обычная функция со своими
   факторами: поле `kind` при чтении отбрасывается. */

/** Новая функция внутри актива: работа людей, конверсия 100% (см. факторы). */
export const newFunc = (e, name = "новая функция") => ({
  id: nextId("f"),
  e,
  name,
  factors: [],
  // Описание — необязательное: чем функция занята, своими словами. Оно
  // едет в каждую её задачу, чтобы исполнителю не приходилось спрашивать,
  // что вообще за работа.
  about: "",
  takes: [],
  gives: [],
  dur: 1,
  // Верхняя граница времени. Новая функция заводится точным сроком:
  // вилка «от 1 до 1» — это то же самое число, только сказанное дважды.
  durHi: 1,
  durUnit: DUR_DEFAULT,
  // Пусто — «сразу»: следующая попытка начинается за предыдущей.
  every: 0,
  everyHi: 0,
  everyUnit: DUR_DEFAULT,
  /* Сколько выполнений идут ОДНОВРЕМЕННО. По умолчанию одно: работа
     делается по очереди, и обещать иное без слов человека нельзя. Больше
     одного — про долгие дела: юрист ведёт восемь дел месяцами разом, и
     считать их друг за другом значило бы обещать восемь месяцев там, где
     выйдет один. */
  par: 1,
  setters: [],
  owners: [],
  reviewers: [],
  /* Принята ли функция человеком. Проверки говорят, что она СОБРАНА
     правильно; «принята» говорит, что автор её дособрал и считает готовой.
     Это разные вещи: заполнено может быть всё, а человек ещё думает. Любая
     последующая правка сбрасывает пометку — иначе зелёная метка врала бы
     про изменённую функцию. */
  accepted: false,
  x: 0,
  y: 0,
});

/**
 * Сколько выполнений этой функции идут одновременно.
 *
 * Настройка про ДОЛГИЕ дела: юрист ведёт восемь дел месяцами разом, и они
 * не выстраиваются в очередь друг за другом. Сама работа от этого быстрее
 * не делается — час работы остаётся часом; меняется только то, сколько
 * таких дел помещается в календарь одновременно.
 *
 * Это НЕ множитель от числа людей (инвариант 6): число исполнителей на
 * скорость не влияет, и здесь оно тоже ни при чём — сказано «сколько их
 * может вести один и тот же воркер», и столько и берётся.
 */
export const parOf = (f = {}) => {
  const n = Math.floor(num(f.par));
  return n > 1 ? n : 1;
};

/* ─────── сколько времени уходит на одно выполнение ───────

   Тоже вилка, как и количества: «от 2 до 4 часов». Одно число здесь было
   бы обещанием, которого никто не давал, — работа редко занимает ровно
   столько, сколько задумано. Стороны разводятся так же, как у ресурсов:
   осторожная оценка берёт верхнюю границу времени, щедрая — нижнюю.

   Когда время известно точно, границы просто равны — для этого в форме
   стоит галочка «одинаковое». */
export const hoursRange = ({ dur, durHi, durUnit } = {}) => {
  const k = DUR_UNITS[durUnit] ?? 1;
  const lo = num(dur) * k;
  const hi = durHi == null ? lo : num(durHi) * k;
  return hi < lo ? { lo: hi, hi: lo } : { lo, hi };
};

/**
 * Длительность в часах — общая мера для сравнения и усреднения.
 *
 * `side` выбирает границу: "lo" — быстрая работа, "hi" — долгая. Без
 * стороны берётся середина вилки: там, где нужна одна цифра (подпись,
 * срок задачи), середина честнее любого края.
 */
export const hoursOf = (f = {}, side) => {
  const { lo, hi } = hoursRange(f);
  if (side === "lo") return lo;
  if (side === "hi") return hi;
  return (lo + hi) / 2;
};

/** Задано ли время одним числом, а не вилкой. */
export const sameHours = (f = {}) => {
  const { lo, hi } = hoursRange(f);
  return lo === hi;
};

/* ─────── через сколько будет следующая попытка ───────

   Тоже вилка, и тоже не длительность: работа может занимать час, а
   следующая попытка случаться через неделю. Ноль значит «сразу»: следующая
   попытка начинается, как только закончилась предыдущая, и всё упирается
   только в саму работу.

   Слово «попытка», а не «повторение», — потому что попытка может и не
   удаться: у фактора есть вероятность, и неудачная попытка просто ничего
   не делает, дожидаясь следующей. */
export const everyRange = ({ every, everyHi, everyUnit } = {}) => {
  const k = DUR_UNITS[everyUnit] ?? 1;
  const lo = num(every) * k;
  const hi = everyHi == null ? lo : num(everyHi) * k;
  return hi < lo ? { lo: hi, hi: lo } : { lo, hi };
};

/**
 * Через сколько часов следующая попытка. Ноль — «сразу».
 *
 * `side` выбирает границу: щедрой оценке достаётся частая попытка (нижняя
 * граница), осторожной — редкая. Без стороны — середина вилки.
 */
export const everyOf = (f = {}, side) => {
  const { lo, hi } = everyRange(f);
  if (side === "hi") return lo;
  if (side === "lo") return hi;
  return (lo + hi) / 2;
};

/** Задан ли срок попытки одним числом, а не вилкой. */
export const sameEvery = (f = {}) => {
  const { lo, hi } = everyRange(f);
  return lo === hi;
};

/* ─────── вероятность, что попытка удастся ───────

   Свойство САМОГО ФАКТОРА, а не функции. Сезон бывает удачным с одной и
   той же вероятностью, сколько бы функций от него ни зависело; спрашивать
   её у каждой функции значило бы задавать один вопрос по нескольку раз и
   получать разные ответы.

   У задачи вероятности нет вовсе: работу делает человек, и «выйдет с
   вероятностью 60%» про неё сказать нельзя — либо назначили, либо нет. */
export const CHANCE_MAX = 100;
const clampChance = (v) => Math.max(0, Math.min(CHANCE_MAX, num(v)));

/** Вероятность одного фактора — так, как она у него записана. */
export const factorChance = (x) => (x?.chance == null ? CHANCE_MAX : clampChance(x.chance));

/* Факторов у функции может быть несколько, и это ПРОСТО СПИСОК, который
   она перебирает за одну попытку. Функция пробует применить первый; не
   вышло — пробует второй, потом третий, и так до конца списка. Хватило
   любого — попытка удалась; не удался ни один — не случилось ничего.

   Перемножения здесь нет и быть не может: перемножение означало бы «нужны
   все сразу», а сказано другое — нужен хоть какой-нибудь. От перемножения
   цепочка выходила бы тем реже, чем больше у неё запасных вариантов, то
   есть запасной вариант вредил бы.

   Прежняя запись — один фактор полем `factor` — читается как список из
   одного: модели, собранные до этого, ничего не теряют. */
export const factorsOf = (f = {}) => (Array.isArray(f.factors)
  ? f.factors.filter(Boolean)
  : (f.factor ? [f.factor] : []));

/**
 * Сколько процентов выпадает функции: попытка удаётся, если удался ХОТЬ ОДИН
 * фактор из списка.
 *
 * Считается через обратное — вероятность, что не удался ни один: у «или»
 * прямой суммы не бывает, два фактора по 60% дают 84%, а не 120%.
 */
export const chanceOf = (f = {}, factors = []) => {
  const ids = factorsOf(f);
  if (!ids.length) return CHANCE_MAX;
  const miss = ids.reduce((p, id) => {
    const x = factors.find((y) => y.id === id);
    return p * (CHANCE_MAX - factorChance(x)) / CHANCE_MAX;
  }, CHANCE_MAX);
  return CHANCE_MAX - miss;
};

/**
 * Конверсия функции — доля от 0 до 1: без факторов 1, с факторами —
 * их шанс. Столько выхода даёт одна порция входа; обратное число — во
 * сколько раз больше входа нужно на одно выполнение (`takeQty`).
 */
export const conversionOf = (f = {}, factors = []) => chanceOf(f, factors) / CHANCE_MAX;

/**
 * Сколько входа нужно на одно выполнение с учётом конверсии: порция /
 * конверсия. Конверсия ноль — входа не хватит никогда (Infinity): фактор,
 * который не случается, ждать бессмысленно, и это сказано числом, а не
 * тихим нулём.
 */
export const takeQty = (qty, conv = 1) => (num(conv) > 0 ? num(qty) / num(conv)
  : (num(qty) > 0 ? Infinity : 0));

/** По-человечески: «сразу» или «через 2 нед», вилкой — «через 1–2 нед». */
export const everyText = (f) => {
  const { lo, hi } = everyRange(f);
  if (lo <= 0 && hi <= 0) return "сразу";
  return sameEvery(f)
    ? `через ${nmDur(f.every)} ${f.everyUnit}`
    : `через ${nmDur(f.every)}–${nmDur(f.everyHi)} ${f.everyUnit}`;
};
const nmDur = (v) => (Math.round(num(v) * 100) / 100);

/**
 * Приведение чужой записи к нынешней.
 *
 * Достраиваем недостающее — не более того. Записи прежних версий (стрелки
 * между элементами, `qty` вместо вилки, сроки и люди на каждом выходе)
 * здесь НЕ переносятся: владелец сказал прямо — прежние модели работать не
 * должны. Молчаливый перенос был бы хуже отказа: получилась бы модель,
 * которую никто не собирал, и разбираться в ней пришлось бы дольше, чем
 * собрать заново.
 */
export const normalizeFunc = (f = {}) => {
  // Вход и выход устроены одинаково. Прежнее поле получателя `to` не
  // читается и не сохраняется: получатель — это актив самого ресурса.
  /* Вход и выход устроены одинаково, кроме одного: «или» бывает только у
     входа. У выхода группа всегда своя — функция выдаёт то, что выдаёт, и
     «выдаст А или Б» без правила, что именно, было бы не моделью, а
     монеткой. Поэтому поле есть, но выразить им у выхода нечего. */
  const port = (p = {}, grouped = false) => {
    const id = p.id ?? nextId("p");
    return {
      id,
      trait: p.trait ?? "",
      lo: num(p.lo),
      hi: num(p.hi),
      group: (grouped && p.group) || id,
      /* Расходует ли вход взятое. Записи, собранные до этого, расходовали
         всегда — поэтому «не сказано» читается как «расходует», а не как
         «нет»: молчание прежней модели не должно менять её смысл. У выхода
         поля нет вовсе — выдавать, не выдавая, нечего. */
      ...(grouped ? { spend: p.spend !== false } : {}),
    };
  };
  const unit = (u) => (DUR_UNITS[u] ? u : DUR_DEFAULT);
  // Прежнее поле одного фактора не остаётся рядом со списком: два места
  // для одного и того же разошлись бы на первой же правке.
  const { factor, kind, ...rest } = f;   // eslint-disable-line no-unused-vars
  return {
    ...rest,
    e: f.e ?? null,
    name: f.name ?? "",
    about: f.about == null ? "" : String(f.about),
    factors: factorsOf(f),
    /* Должности ролей и исключения — часть записи функции. Старые списки
       людей в `setters/owners/reviewers` остаются: по ним читаются схемы,
       собранные до должностей. */
    posts: Object.fromEntries(WORKER_KINDS.map((k) => [k.id, postsOf(f, k.id)])),
    except: exceptOf(f),
    takes: Array.isArray(f.takes) ? f.takes.map((p) => port(p, true)) : [],
    gives: Array.isArray(f.gives) ? f.gives.map((p) => port(p)) : [],
    dur: num(f.dur),
    // Записи без верхней границы — это точный срок, а не сломанная вилка.
    durHi: f.durHi == null ? num(f.dur) : num(f.durHi),
    durUnit: unit(f.durUnit),
    every: num(f.every),
    everyHi: f.everyHi == null ? num(f.every) : num(f.everyHi),
    everyUnit: unit(f.everyUnit),
    /* Меньше одного одновременного выполнения не бывает: ноль означал бы,
       что работа не делается вовсе, а этого поле не про то. Дробей тут
       тоже нет — половины дела в работе не держат. */
    par: parOf(f),
    ...Object.fromEntries(WORKER_KINDS.map((k) => [k.id,
      [...new Set(Array.isArray(f[k.id]) ? f[k.id] : [])]])),
    // Прежние модели пометки не знали: молчание читается как «не принята».
    accepted: f.accepted === true,
    x: num(f.x),
    y: num(f.y),
  };
};

export const normalizeFuncs = (list) =>
  (Array.isArray(list) ? list.map(normalizeFunc) : []);

/** Обратно в удобные единицы: 36 часов — это «1.5 дн», а не «36 ч». */
export function fromHours(h) {
  const n = num(h);
  const unit = ["мес", "нед", "дн", "ч"].find((u) => n >= DUR_UNITS[u]) || "ч";
  return { dur: Math.round((n / DUR_UNITS[unit]) * 10) / 10, durUnit: unit };
}

/**
 * Среднее арифметическое по фактическим выполнениям.
 *
 * Считается только по состоявшимся: незакрытое выполнение ничего не
 * измеряет, а взятое в расчёт занижало бы среднее ровно тогда, когда
 * работа идёт.
 */
export const avgOf = (list = []) => {
  const done = list.map(Number).filter((v) => Number.isFinite(v) && v > 0);
  if (!done.length) return null;
  return done.reduce((s, v) => s + v, 0) / done.length;
};

/**
 * Выполнение функции — это `{hours, takes:{ресурс:сколько}, gives:{…}}`.
 * Отсюда и берётся «в реальных показывается среднеарифметическое».
 */
export const runHours = (runs = []) => avgOf(runs.map((r) => r?.hours));
export const runQty = (runs = [], kind, trait) =>
  avgOf(runs.map((r) => r?.[kind]?.[trait]));

/** Вилка по-человечески: «от 3 до 5», «ровно 4», «от 3». */
export const rangeText = (p) => {
  const lo = num(p?.lo);
  const hi = num(p?.hi);
  if (!lo && !hi) return "сколько — не задано";
  if (lo === hi) return `ровно ${lo}`;
  if (!hi) return `от ${lo}`;
  if (!lo) return `до ${hi}`;
  return `от ${lo} до ${hi}`;
};

/**
 * Годна ли вилка.
 *
 * Перевёрнутая — не мелочь: «от 5 до 3» молча считалась бы как попало, а
 * человек был бы уверен, что задал границы. Пустая тоже не годится:
 * ресурс в рецепте без количества ничего не переносит.
 */
export const okRange = (p) => {
  const lo = num(p?.lo);
  const hi = num(p?.hi);
  return hi >= lo && (lo > 0 || hi > 0);
};

/* ─────── что задача ОБЯЗАНА выдать вещью ───────

   Функция выдаёт не число, а вещь: техническое задание, макет, договор.
   Число в сдаче говорит «одна штука» и молчит о том, какая именно, — а
   спрашивают потом именно вещь: «покажи вот этот макет». Поэтому при сдаче
   исполнителю предлагается приложить то, что у него вышло, по каждому
   выдаваемому ресурсу.

   Обязательным считается ресурс, у которого НИЖНЯЯ граница вилки больше
   нуля: функция обещала выдать хотя бы столько, и работа без этого не
   сделана. Ноль внизу вилки — прямое разрешение не выдать ничего («может
   выйти, а может и нет»), и требовать файл там не за что. */
export const requiredGives = (f) => (f?.gives || [])
  .filter((p) => p && p.trait && num(p.lo) > 0);

/**
 * Чего в сдаче не хватает: обязательный выход без приложенной вещи.
 *
 * Пустой список — сдавать можно. Непустой — задача не выполнена, и сказать
 * это надо до нажатия, а не молчаливо принять сдачу без результата.
 */
export const missingGives = (f, files = {}) =>
  requiredGives(f).filter((p) => !(files || {})[p.trait]);

/* ════════════════════════════════════════════════════════════════
   ВОРКЕРЫ АКТИВА

   У актива три вида людей — это его воркеры:

   · постановщики (`setters`) — те, кто ставит задачу и пишет, что в ней
     сделать;
   · исполнители (`owners`) — те, кто её выполняет;
   · проверяющие (`reviewers`) — те, кто принимает отчёт.

   Все три обязательны: без постановщика непонятно, кто описал работу; без
   исполнителя её некому делать; без проверяющего некому принять, а значит
   сделанное не попадёт в расчёт.

   Функции выполняют они же, поэтому назначить на функцию можно только
   воркера её актива.
   ════════════════════════════════════════════════════════════════ */

const ids = (v) => (Array.isArray(v) ? [...new Set(v.filter((x) => x != null))] : []);

/** Три вида воркеров — в одном месте, чтобы нигде не забыть третий. */
/* ─────── неделя ───────

   Дни считаются с понедельника: неделя начинается с рабочего дня. Список
   один на всё приложение — и цель, и рабочий график человека называют дни
   одинаково; два списка разошлись бы в порядке или в сокращениях, и «пн»
   в одном месте значило бы не то, что в другом. */
export const WEEK = [
  { id: 1, short: "пн" }, { id: 2, short: "вт" }, { id: 3, short: "ср" },
  { id: 4, short: "чт" }, { id: 5, short: "пт" }, { id: 6, short: "сб" },
  { id: 0, short: "вс" },
];

/* ─────── роль — это ДОЛЖНОСТЬ, а не человек ───────

   Прежде на функцию назначали конкретных людей. Владелец это снял: у
   функции стоят ДОЛЖНОСТИ («юрист ставит, дизайнер делает, редактор
   принимает»), а взять работу может любой воркер актива с такой
   должностью. Человек в функции больше не записан — записана роль, и
   уволившийся дизайнер не уносит с собой половину схемы.

   Исключения (`except`) — обратная сторона: «этот дизайнер эту функцию не
   берёт». Список людей, а не должностей: исключение всегда про человека.

   Старая запись (люди в `setters/owners/reviewers`) читается как была: где
   должность у роли не названа, а люди записаны, назначать дают их —
   иначе выкат сломал бы уже собранные схемы. */
export const postsOf = (f = {}, role) => {
  const all = f && typeof f.posts === "object" && f.posts ? f.posts : {};
  const list = Array.isArray(all[role]) ? all[role] : [];
  return [...new Set(list.map((x) => String(x)).filter(Boolean))];
};

/** Поставить или снять должность у роли функции. */
export const togglePost = (f = {}, role, posId) => {
  const key = String(posId || "");
  if (!key) return f;
  const now = postsOf(f, role);
  const next = now.includes(key) ? now.filter((x) => x !== key) : [...now, key];
  return { ...f, posts: { ...(f.posts || {}), [role]: next } };
};

/** Кому эта функция закрыта, хотя должность подходит. */
export const exceptOf = (f = {}) => (Array.isArray(f.except)
  ? [...new Set(f.except.map((x) => String(x)).filter(Boolean))] : []);

export const toggleExcept = (f = {}, personId) => {
  const key = String(personId || "");
  if (!key) return f;
  const now = exceptOf(f);
  return { ...f, except: now.includes(key) ? now.filter((x) => x !== key) : [...now, key] };
};

/**
 * Кого можно назначить на роль функции: воркеры актива с нужной должностью,
 * кроме исключённых. Должность роли не названа — читается старый список
 * людей; нет и его — никого (это ответ, а не «значит, всех»).
 */
export function eligible(f, role, { crew = [], positionOf = () => "", people = [] } = {}) {
  if (!f) return [];
  const ids = crew.length ? crew.map(String)
    : people.map((p) => String(p.id ?? p));
  const posts = postsOf(f, role);
  const legacy = (Array.isArray(f[role]) ? f[role] : []).map(String);
  const banned = new Set(exceptOf(f));
  const base = posts.length
    ? ids.filter((id) => posts.includes(String(positionOf(id) || "")))
    : ids.filter((id) => legacy.includes(id));
  return base.filter((id) => !banned.has(id));
}

/** Доступна ли функция человеку по должности (до исключений). */
export const byPost = (f, role, positionOf, id) => {
  const posts = postsOf(f, role);
  return posts.length ? posts.includes(String(positionOf(id) || ""))
    : (Array.isArray(f?.[role]) ? f[role] : []).map(String).includes(String(id));
};

/**
 * Что человеку поручено — по всем активам сразу.
 *
 * Список того, где он выбран: актив, функция, в каких ролях и не отказался
 * ли он от неё. Собирается по должности (`byPost`), а не по имени в
 * функции: назначает должность, человек только отказывается.
 *
 * Нужен в анкете: настройки актива человек не видит, а знать, что на нём
 * висит, должен — и отказаться тоже.
 */
export function dutyOf({ funcs = [], entities = [] } = {}, personId,
  { positionOf = () => "" } = {}) {
  const id = String(personId ?? "");
  if (!id) return [];
  const crewOfAsset = (e) => new Set(crewOf(workersOf(entities, e)).map(String));
  const inCrew = {};
  return funcs.map((f) => {
    if (!(f.e in inCrew)) inCrew[f.e] = crewOfAsset(f.e);
    if (!inCrew[f.e].has(id)) return null;
    const roles = WORKER_KINDS.filter((k) => byPost(f, k.id, positionOf, id)).map((k) => k.id);
    if (!roles.length) return null;
    const e = entities.find((x) => x.id === f.e) || null;
    return { func: f.id, name: f.name || "без названия", asset: f.e,
      assetName: e?.name || "актив удалён", roles,
      off: exceptOf(f).includes(id) };
  }).filter(Boolean);
}

export const WORKER_KINDS = [
  { id: "setters", one: "постановщик", many: "постановщики", task: "постановщик" },
  { id: "owners", one: "исполнитель", many: "исполнители", task: "исполнитель" },
  { id: "reviewers", one: "проверяющий", many: "проверяющие", task: "проверяющий" },
];

/** Достраивает актив до нынешней записи: у него есть воркеры и их порядок. */
export const normalizeAsset = (e = {}) => ({
  ...e,
  crew: ids(e.crew),
  ...Object.fromEntries(WORKER_KINDS.map((k) => [k.id, ids(e[k.id])])),
});

export const normalizeAssets = (list) =>
  (Array.isArray(list) ? list.map(normalizeAsset) : []);

/** Воркеры актива: постановщики, исполнители и проверяющие. */
export const workersOf = (entities = [], id) => {
  const e = entities.find((x) => x.id === id);
  // Порядок людей — часть того же ответа: без него список воркеров пришлось
  // бы собирать в двух местах и надеяться, что они не разойдутся.
  return { crew: ids(e?.crew),
    ...Object.fromEntries(WORKER_KINDS.map((k) => [k.id, ids(e?.[k.id])])) };
};

/**
 * Сколько у актива воркеров — ЛЮДЕЙ, а не назначений.
 *
 * Один человек может быть и постановщиком, и исполнителем, и проверяющим
 * сразу — в маленькой команде это норма, а не ошибка. Складывать длины
 * трёх списков значило бы посчитать одного человека трижды и написать
 * «3 воркера» там, где работает один. Число на вкладке отвечает на вопрос
 * «сколько нас», а не «сколько галочек проставлено».
 */
export const countWorkers = (workers = {}) => crewOf(workers).length;

/* ─────── воркеры актива одним списком ───────

   Роли — это про то, кто чем занят, а список воркеров отвечает на другой
   вопрос: КТО ВООБЩЕ РАБОТАЕТ В ЭТОМ АКТИВЕ. Один человек может быть и
   постановщиком, и исполнителем, и проверяющим — в списке он один раз.

   Членство хранится в `crew` и задаётся прямо: сперва отмечают воркеров
   актива из всех людей схемы, и уже из отмеченных выбирают постановщиков,
   исполнителей и проверяющих. Обратный порядок — «стал воркером, потому
   что его куда-то назначили» — заставлял бы называть роль раньше, чем
   человека, и список воркеров был бы подписью под тем, что задано в
   другом месте.

   Назначенный в роль считается воркером и без отметки: так открываются
   модели, собранные прежним порядком, — иначе люди из ролей просто
   исчезли бы из актива. */
export const crewOf = (workers = {}) => {
  const out = [];
  const push = (id) => {
    if (id != null && !out.some((x) => String(x) === String(id))) out.push(id);
  };
  ids(workers.crew).forEach(push);
  WORKER_KINDS.forEach((k) => ids(workers[k.id]).forEach(push));
  return out;
};

/** Воркер ли человек в этом активе. */
export const isCrew = (workers = {}, id) =>
  crewOf(workers).some((x) => String(x) === String(id));

/** Место человека в порядке актива: чем меньше, тем выше в списках. */
export const crewRank = (workers = {}) => {
  const order = crewOf(workers).map(String);
  return (id) => {
    const i = order.indexOf(String(id));
    return i < 0 ? order.length : i;
  };
};

/** Тот же порядок, но применённый к готовому списку людей. */
export const byCrew = (workers, people = []) => {
  const rank = crewRank(workers);
  return [...people].sort((a, b) => rank(a?.id ?? a) - rank(b?.id ?? b));
};

/**
 * Чего не хватает, чтобы функцию можно было выполнить прямо сейчас.
 *
 * Возвращает список нехваток: по одной на каждое требование, которое нечем
 * закрыть. Внутри требования достаточно ОДНОГО подходящего варианта — на то
 * оно и «или»; не хватает, только если не хватает всех сразу.
 *
 * Считается по верхней границе вилки — по тому, сколько может понадобиться.
 * Взяться за работу, зная, что ресурса хватит лишь в удачном случае, —
 * значит заранее согласиться встать на полпути.
 *
 * `done` — сколько единиц каждого ресурса ЭТА функция уже обработала, не
 * расходуя. Обработанное лежит на месте и достаётся другим функциям, но
 * этой второй раз не даётся: работа по нему уже сделана.
 */
export function shortage(f, traits = [], done = {}, factors = []) {
  if (!f) return [];
  /* Конверсия: с факторами на 10% входа нужно вдесятеро больше — задача
     уходит на постановку, когда набралось столько. Владелец: «единиц
     забираемого ресурса должно стать 10, прежде чем задача уйдёт». */
  const conv = conversionOf(f, factors);
  const req = (p) => takeQty(num(p.hi || p.lo), conv);
  const left = (id) => num(done?.[id]);
  const have = (id) => {
    const all = num(traits.find((t) => t.id === id)?.have);
    return all;
  };
  const free = (p) => (portSpends(p) ? have(p.trait)
    : Math.max(0, have(p.trait) - left(p.trait)));
  const name = (id) => traits.find((t) => t.id === id)?.l || "(ресурс удалён)";
  return groupsOf(f.takes || [])
    .map((g) => {
      const ok = g.some((p) => free(p) >= req(p));
      if (ok) return null;
      // Показываем тот вариант, которого не хватает меньше всего: до него
      // ближе всего, и именно он подскажет, чего добирать.
      const best = g.reduce((a, p) => {
        const gap = req(p) - free(p);
        return a && a.gap <= gap ? a : { p, gap };
      }, null);
      return best && {
        trait: best.p.trait,
        name: name(best.p.trait),
        need: req(best.p),
        have: free(best.p),
        // Обработанное этой функцией: не «нет ресурса», а «нет НОВОГО».
        done: portSpends(best.p) ? 0 : Math.min(left(best.p.trait), have(best.p.trait)),
        spend: portSpends(best.p),
        alts: g.length,
      };
    })
    .filter(Boolean);
}

/** Хватает ли ресурсов, чтобы взяться за функцию прямо сейчас. */
export const canRun = (f, traits = [], done = {}) => shortage(f, traits, done).length === 0;

/**
 * Людей, переставших быть воркерами актива, убираем и с его функций.
 *
 * Иначе исполнитель остался бы назначенным, не значась в активе: задача
 * висела бы на человеке, которого в этом активе уже нет.
 */
/**
 * Единственная дверь, через которую функцию правят.
 *
 * Пометка «принята» — слово человека о ТОЙ функции, которую он видел. Значит
 * снимать её должна ЛЮБАЯ правка, откуда бы та ни пришла: из формы функции,
 * из удаления ресурса на соседней вкладке, из снятия человека с актива. Пока
 * сброс жил в одной панели, удаление ресурса тихо меняло рецепт принятой
 * функции, а она оставалась зелёной — то есть ровно то, что пометка обязана
 * исключать.
 *
 * И наоборот: правка, которая ничего не изменила, пометку не трогает.
 * Поля отдают значение по расфокусу, и клик мимо поля — не правка: иначе
 * «принято» слетало бы от того, что человек ткнул в название и передумал, а
 * в историю падал бы шаг за действие, которого никто не совершал.
 *
 * Координаты на схеме не в счёт: подвинуть карточку — не значит переделать
 * работу.
 */
export function editFunc(f, make) {
  const next = typeof make === "function" ? make(f) : make;
  if (!f || !next) return next;
  const bare = ({ accepted, x, y, ...rest }) => rest;
  const same = JSON.stringify(bare(f)) === JSON.stringify(bare(next));
  return same ? { ...next, accepted: f.accepted } : { ...next, accepted: false };
}

export const pruneWorkers = (funcs = [], id, workers) => {
  /* Кого оставляем — ВОРКЕРОВ актива, одинаково для всех трёх ролей: роли
     живут у функции, и списков ролей у актива больше нет. Сняли человека с
     актива — он уходит отовсюду, где был назначен; остался — назначения
     не трогаются. */
  const keep = new Set(crewOf(workers || {}).map(String));
  return funcs.map((f) => (f.e !== id ? f : editFunc(f, (x) => ({
    ...x,
    ...Object.fromEntries(WORKER_KINDS.map((k) => [k.id,
      (x[k.id] || []).filter((p) => keep.has(String(p)))])),
  }))));
};

/* ════════════════════════════════════════════════════════════════
   ПРОВЕРКИ СТРОЕНИЯ

   Три подписи на схеме — «актив», «функция», «ресурс» — белые, пока
   строение сходится, и красные, когда нет. Тексты определений даны
   владельцем и здесь только переведены на нынешние слова: прежде связи
   задавались стрелками «актив → ресурс», теперь — функциями, и говорить
   о стрелках, которых больше нет, значило бы объяснять непонятным.

   Проверка структурная и от времени не зависит: она отвечает на вопрос
   «так ли собрано», а не «сколько сейчас чего». Поэтому ползунок времени
   на цвет подписи не влияет.

   Только что заведённый узел красный сразу — это и есть подсказка, что
   его надо достроить, а не поломка.
   ════════════════════════════════════════════════════════════════ */

export const WHY_ASSET = "Актив — это то, что берёт один ресурс из внешней системы"
  + " и выдаёт другой. Состоит он из воркеров — постановщиков, исполнителей"
  + " и проверяющих, —"
  + " функций, которые они выполняют, и ресурсов, которые эти функции потребляют"
  + " и передают. Подпись краснеет, когда не сходится строение: у актива должна"
  + " быть хотя бы одна функция, хотя бы одна из них должна брать ресурс другого"
  + " актива — это и есть внешний ресурс, — и созданное должно уходить наружу:"
  + " либо функция выдаёт ресурс другого актива, либо чужая функция забирает"
  + " ресурс этого. Людей проверка не требует: пока их не завели,"
  + " работать некому, но собран актив уже может быть верно.";

/* Описание функции — определение и чек-лист, а не рассказ. Прежде здесь
   лежал абзац из семи предложений: про внешний и внутренний ресурс, про
   передачу в чужой актив, про диапазоны, про среднее по выполнениям, про
   время, про задачу и фактор. Человек его не дочитывал, а главное — в нём
   не было видно, ЧТО именно надо сделать. Теперь строка определения и
   список условий, и это ровно те условия, которые проверяет `funcGaps`:
   один и тот же ответ в двух местах, а не два разных рассказа. */
export const WHY_FUNC = "Функция обменивает одни ресурсы на другие."
  + "\n\nЧтобы быть частью актива, ей нужно:"
  + "\n· что берёт — хотя бы один ресурс;"
  + "\n· что выдаёт — хотя бы один ресурс;"
  + "\n· сколько берёт и выдаёт — диапазон «от и до»;"
  + "\n· за какое время выполняется;"
  + "\n· ресурсы: хотя бы один свой — из одних чужих функция не часть актива;"
  + "\n· кто выполняет: постановщик, исполнитель, проверяющий;"
  + "\n· факторы — по желанию: это конверсия, во сколько раз больше входа нужно.";

export const WHY_TRAIT = "Ресурс — это то, что есть. Сам он не изменяется: его"
  + " берут и выдают функции. Чтобы ресурс был задействован в активе, хотя бы"
  + " одна функция должна его выдавать и хотя бы одна — брать. Иначе он либо"
  + " берётся ниоткуда, либо копится и никому не нужен.";

/**
 * Актив: есть функции, есть вход извне и выход наружу.
 *
 * «Извне» и «наружу» — это функции, и решает всё то, чьи ресурсы они
 * трогают: вход ресурсом чужого актива и выход ресурсом чужого актива.
 * Отдельного «получателя» у выхода нет — актив-получатель это тот, кому
 * принадлежит выдаваемый ресурс.
 */
export function checkAsset(id, { funcs = [], traits = [] } = {}) {
  const mine = funcs.filter((f) => f.e === id);
  const own = new Set(traits.filter((t) => t.e === id).map((t) => t.id));
  const outside = mine.some((f) => f.takes.some((p) => !own.has(p.trait)));
  // Созданное уходит наружу двумя способами, и оба законны: функция актива
  // выдаёт ресурс чужого актива — это и есть передача, — либо чужая функция
  // берёт его ресурс.
  // Требовать только первый значило бы красить в красный половину моделей,
  // где ресурс забирают, а не отдают.
  const inside = mine.some((f) => f.gives.some((g) => !own.has(g.trait)))
    || funcs.some((f) => f.e !== id && f.takes.some((p) => own.has(p.trait)));
  // Воркеров проверка не требует намеренно. Людей в модели может не быть
  // вовсе — их заводит владелец, — и красная подпись у каждого актива в
  // первый день не значила бы ничего: красный, который горит везде,
  // перестаёт быть сигналом.
  return { ok: mine.length > 0 && outside && inside, why: WHY_ASSET };
}

/**
 * Ресурс: кто-то его выдаёт и кто-то берёт.
 *
 * Мягко: считается любая функция, а не только функция своего актива, —
 * передача из чужого актива тоже приносит ресурс. Строгое чтение
 * покрасило бы в день переноса половину модели, а красный, который горит
 * везде, перестаёт что-либо значить.
 */
export function checkTrait(id, { traits = [], funcs = [] } = {}) {
  if (!traits.some((t) => t.id === id)) return { ok: false, why: WHY_TRAIT };
  const made = funcs.some((f) => f.gives.some((g) => g.trait === id));
  const used = funcs.some((f) => f.takes.some((p) => p.trait === id));
  return { ok: made && used, why: WHY_TRAIT };
}

/**
 * Функция: либо преобразование целиком внутри актива, либо ресурсы и
 * наружу, и внутрь. Ничего не берущая или ничего не выдающая функция не
 * преобразует ничего — она тоже красная.
 *
 * «Наружу» — про РЕСУРС: наружным считается ресурс чужого актива, и это
 * же решает, куда уходит выданное. Функция, которая берёт внешний ресурс и
 * делает из него свой, — самая обычная, и красить её не за что.
 *
 * Вилки и время проверяются здесь же, а не «потом при расчёте»: функция
 * без количества и без срока выглядит заполненной, но не говорит ни
 * сколько ресурса уйдёт, ни когда будет готово, — и в прогнозе окажется
 * невидимым нулём.
 */
export function checkFunc(f, ctx = {}) {
  return { ok: funcGaps(f, ctx).length === 0, why: WHY_FUNC };
}

/**
 * Чего функции не хватает, чтобы быть собранной, — словами и по пунктам.
 *
 * Один список на два места: он красит подпись и называет, чего нет, он же
 * перечислен в описании функции. Два отдельных ответа на один вопрос
 * разошлись бы в первый же день.
 *
 * Список — подсказка, а не запрет: «Принять» нажимается всегда, и что
 * функция годится, решает человек, а не проверка. Пусто — значит собрано.
 */
export function funcGaps(f, { traits = [], factors = [] } = {}) {
  if (!f) return ["функции нет"];
  const out = [];
  if (!f.takes?.length) out.push("не сказано, что берёт");
  if (!f.gives?.length) out.push("не сказано, что выдаёт");
  /* Факторы — по желанию, но названные должны существовать и быть своими:
     сезон одного актива не двигает ресурсы другого. Чужой или удалённый в
     списке — ошибка ссылки; выбрать такой форма не даёт, а в старой
     записи он мог остаться. Список факторов дают не всегда: там, где его
     нет, ссылку не проверяем. */
  if (factors.length > 0) {
    const found = factorsOf(f).map((id) => factors.find((x) => x.id === id));
    if (found.some((x) => !x)) out.push("выбран удалённый фактор");
    else if (found.some((x) => x.e !== f.e)) out.push("выбран фактор другого актива");
  }
  const ports = [...(f.takes || []), ...(f.gives || [])];
  // Ссылка на удалённый ресурс — не «наружу», а обрыв: функция с ней не
  // преобразует ничего, и зелёной ей быть не за что.
  if (ports.some((p) => !traits.some((t) => t.id === p.trait))) {
    out.push("есть ссылка на удалённый ресурс");
  }
  if (ports.some((p) => !okRange(p))) out.push("диапазон «от и до» задан неверно");
  /* Обе границы времени должны быть заданы: «от 0 до 4 часов» не говорит,
     когда будет готово, — оно говорит «может быть, мгновенно». */
  const h = hoursRange(f);
  if (!(h.lo > 0) || !(h.hi > 0)) out.push("не задано время выполнения");
  const own = new Set(traits.filter((t) => t.e === f.e).map((t) => t.id));
  const outer = ports.filter((p) => !own.has(p.trait)).length;
  const inner = ports.length - outer;
  if (ports.length && outer > 0 && inner === 0) {
    out.push("все ресурсы чужие — функция не часть актива");
  }
  return out;
}

/**
 * Состояние функции для показа: принята ли и, если нет, собрана ли.
 *
 * Два цвета, три состояния — так просил владелец. Зелёное — одно:
 * «готова», и ставит его человек кнопкой «Принять». Красных два, и они
 * различаются подписью, а не оттенком: «не заполнена» (и названо, чего не
 * хватает) и «не принята» (собрана, кнопку не нажимали).
 *
 * Принятая функция зелёная, даже если проверка ещё что-то находит:
 * «Принять» — слово человека, и оно старше подсказки. Пробелы в ответе
 * остаются, но красить ими принятое нельзя — иначе кнопка была бы обманом.
 */
export function funcState(f, ctx = {}) {
  const gaps = funcGaps(f, ctx);
  if (f?.accepted) return { kind: "ready", ok: true, word: "готова", gaps };
  if (gaps.length) return { kind: "gaps", ok: false, word: "не заполнена", gaps };
  return { kind: "draft", ok: true, word: "не принята", gaps };
}



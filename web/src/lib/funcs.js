export const normalizeFactor = (x = {}) => ({
  ...x,
  id: x.id ?? nextId("x"),
  e: x.e ?? null,
  name: x.name ?? "",
  chance: x.chance == null ? CHANCE_MAX : clampChance(x.chance),
});
export const normalizeFactors = (list) =>
  (Array.isArray(list) ? list.map(normalizeFactor) : []);

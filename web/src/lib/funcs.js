/* ════════════════════════════════════════════════════════════════
   ФУНКЦИИ АКТИВА

   Ресурс — это то, что есть. Функция — то, что его преобразует: берёт
   одни ресурсы и выдаёт другие, и на это уходит время.

   ─── что из чего состоит ───

   Актив
     ├── воркеры: исполнители и проверяющие — люди, которые в нём работают;
     ├── функции: то, что эти люди выполняют;
     └── ресурсы: то, что функции при этом потребляют и передают.

   Воркеры актива не заводятся отдельным списком: это ровно те люди, что
   назначены на его функции. Отдельный список пришлось бы держать в
   согласии с назначениями вручную, и он бы разошёлся с ними в первый же
   день.

   ─── как устроена запись функции ───

   Функция живёт внутри актива (`e`) и связана с ресурсами двумя списками:

   · takes — что берёт: [{trait, lo, hi}]
   · gives — что выдаёт: [{trait, lo, hi}]

   Ресурс из чужого актива в выходах и означает передачу: функция берёт
   своё и отдаёт наружу, в другой актив. Отдельного «кому передать» здесь
   нет и быть не должно — ресурс уже принадлежит активу, и второе поле
   рядом с ним разошлось бы с первым.

   ─── про диапазоны ───

   Сколько ресурса функция возьмёт и сколько выдаст — это не число, а
   вилка `lo`..`hi`. Сначала она закладывается как гипотеза, потом
   уточняется на реальных выполнениях: по ним считается среднее
   арифметическое, и оно показывается рядом с планом.

   Одно точное число здесь было бы обещанием, которого никто не давал, а
   план, выданный за факт, — обманом. Поэтому и цвета разные: план
   жёлтый, факт зелёный.

   ─── про время ───

   `dur` — длительность ОДНОГО выполнения функции: «за какое время
   дизайнер сделает дизайн страницы». Не производительность за период.
   Время у функции одно: выполнение либо случилось целиком, либо нет, и
   раздавать разным её выходам разные сроки не за что.
   ════════════════════════════════════════════════════════════════ */

/** Единицы длительности. Значение — сколько в них часов. */
export const DUR_UNITS = { ч: 1, дн: 24, нед: 168, мес: 730 };
export const DUR_DEFAULT = "дн";

let seq = 0;
const nextId = (prefix) => {
  seq += 1;
  return `${prefix}${Date.now().toString(36)}${seq.toString(36)}`;
};

const num = (v) => Number(v) || 0;

/**
 * Вход или выход функции: ресурс и вилка «сколько».
 *
 * Новый порт заводится вилкой 1..1 — не нулём: ноль означал бы «ресурс
 * есть в рецепте, но не расходуется», а это не то, что человек имел в
 * виду, нажимая «+ берёт».
 */
export const newPort = (trait = "", lo = 1, hi = 1) => ({
  id: nextId("p"),
  trait,
  lo: num(lo),
  hi: num(hi),
});

/** Новая функция внутри актива. */
export const newFunc = (e, name = "новая функция") => ({
  id: nextId("f"),
  e,
  name,
  takes: [],
  gives: [],
  dur: 1,
  durUnit: DUR_DEFAULT,
  owners: [],
  reviewers: [],
  x: 0,
  y: 0,
});

/** Длительность в часах — общая мера для сравнения и усреднения. */
export const hoursOf = ({ dur, durUnit } = {}) =>
  num(dur) * (DUR_UNITS[durUnit] ?? 1);

/**
 * Приведение к нынешней записи — и починка прежней.
 *
 * Прежде у функции было три формы вместо двух: «берёт», «выдаёт» и
 * «передаёт другим». Выходом считалась отдельная функция, и срок,
 * исполнители и проверяющие висели на каждом выходе свои. Это оказалось
 * неверно: функция одна, у неё одно время выполнения и одни люди, а
 * выходов у неё может быть несколько.
 *
 * Поэтому старая запись сводится к новой:
 * · qty входа и выхода становится вилкой qty..qty — ровно столько,
 *   сколько было заложено, без выдумывания границ;
 * · срок функции берётся самый долгий из сроков её выходов: выполнение
 *   кончается тогда, когда готово всё, а не когда готова первая часть;
 * · исполнители и проверяющие складываются со всех выходов — терять
 *   назначенного человека нельзя, он уже в работе.
 */
export const normalizeFunc = (f = {}) => {
  const port = (p = {}) => {
    // Старая запись знает только qty; новая — вилку. Отличаем по наличию
    // границ, а не по нулю: вилка 0..0 законна и значит «не задано».
    const ranged = p.lo != null || p.hi != null;
    return {
      id: p.id ?? nextId("p"),
      trait: p.trait ?? "",
      lo: ranged ? num(p.lo) : num(p.qty),
      hi: ranged ? num(p.hi ?? p.lo) : num(p.qty),
    };
  };
  const olds = Array.isArray(f.gives) ? f.gives : [];
  const legacy = Math.max(0, ...olds.map(hoursOf));
  const legacyPeople = (k) => olds.flatMap((g) => (Array.isArray(g[k]) ? g[k] : []));
  const time = f.dur != null
    ? { dur: num(f.dur), durUnit: DUR_UNITS[f.durUnit] ? f.durUnit : DUR_DEFAULT }
    : (legacy > 0 ? fromHours(legacy) : { dur: 0, durUnit: DUR_DEFAULT });

  return {
    ...f,
    e: f.e ?? null,
    name: f.name ?? "",
    takes: Array.isArray(f.takes) ? f.takes.map(port) : [],
    gives: olds.map(port),
    ...time,
    owners: [...new Set(Array.isArray(f.owners) ? f.owners : legacyPeople("owners"))],
    reviewers: [...new Set(Array.isArray(f.reviewers) ? f.reviewers : legacyPeople("reviewers"))],
    x: num(f.x),
    y: num(f.y),
  };
};

export const normalizeFuncs = (list) =>
  (Array.isArray(list) ? list.map(normalizeFunc) : []);

/**
 * Приём документа: функции вместе с прежними стрелками между ними.
 *
 * Третья форма — «передаёт другим элементам» — была отдельным списком
 * `flows`. Теперь передача выражается выходом: функция выдаёт ресурс, и
 * если ресурс чужого актива — значит передала туда. Стрелки старых
 * моделей поэтому не выбрасываются, а вливаются в выходы: у кого вилка
 * уже задана — остаётся своя, у кого выхода не было — появляется с
 * вилкой стрелки. Молча потерять заложенные числа нельзя.
 */
export const adoptFuncs = (list, flows) => {
  const fs = normalizeFuncs(list);
  if (!Array.isArray(flows) || !flows.length) return fs;
  return fs.map((f) => {
    const mine = flows.filter((w) => w && w.from === f.id && w.trait);
    if (!mine.length) return f;
    const gives = [...f.gives];
    mine.forEach((w) => {
      const at = gives.findIndex((g) => g.trait === w.trait);
      if (at < 0) gives.push(newPort(w.trait, num(w.lo), num(w.hi)));
      else if (!gives[at].lo && !gives[at].hi) {
        gives[at] = { ...gives[at], lo: num(w.lo), hi: num(w.hi) };
      }
    });
    return { ...f, gives };
  });
};

/** Обратно в удобные единицы: 36 часов — это «1.5 дн», а не «36 ч». */
export function fromHours(h) {
  const n = num(h);
  const unit = ["мес", "нед", "дн", "ч"].find((u) => n >= DUR_UNITS[u]) || "ч";
  return { dur: Math.round((n / DUR_UNITS[unit]) * 10) / 10, durUnit: unit };
}

/**
 * Сколько выполнений функции помещается в один шаг прогноза.
 *
 * Шаг модели — месяц. Цикл короче месяца повторяется несколько раз; цикл
 * длиннее месяца выдаёт долю — иначе результат, на который ушло полгода,
 * появлялся бы разом и модель врала бы о сроках.
 */
export const cyclesPerMonth = (f) => {
  const h = hoursOf(f);
  return h > 0 ? DUR_UNITS["мес"] / h : 0;
};

/**
 * Среднее арифметическое по фактическим выполнениям.
 *
 * Считается только по состоявшимся: незакрытое выполнение ничего не
 * измеряет, а взятое в расчёт занижало бы среднее ровно тогда, когда
 * работа идёт.
 */
export const avgOf = (list = []) => {
  const done = list.map(Number).filter((v) => Number.isFinite(v) && v > 0);
  if (!done.length) return null;
  return done.reduce((s, v) => s + v, 0) / done.length;
};

/**
 * Выполнение функции — это `{hours, takes:{ресурс:сколько}, gives:{…}}`.
 * Отсюда и берётся «в реальных показывается среднеарифметическое».
 */
export const runHours = (runs = []) => avgOf(runs.map((r) => r?.hours));
export const runQty = (runs = [], kind, trait) =>
  avgOf(runs.map((r) => r?.[kind]?.[trait]));

/** Вилка по-человечески: «от 3 до 5», «ровно 4», «от 3». */
export const rangeText = (p) => {
  const lo = num(p?.lo);
  const hi = num(p?.hi);
  if (!lo && !hi) return "сколько — не задано";
  if (lo === hi) return `ровно ${lo}`;
  if (!hi) return `от ${lo}`;
  if (!lo) return `до ${hi}`;
  return `от ${lo} до ${hi}`;
};

/**
 * Годна ли вилка.
 *
 * Перевёрнутая — не мелочь: «от 5 до 3» молча считалась бы как попало, а
 * человек был бы уверен, что задал границы. Пустая тоже не годится:
 * ресурс в рецепте без количества ничего не переносит.
 */
export const okRange = (p) => {
  const lo = num(p?.lo);
  const hi = num(p?.hi);
  return hi >= lo && (lo > 0 || hi > 0);
};

/** Воркеры актива — люди с его функций: исполнители и проверяющие. */
export const workersOf = (funcs = [], e) => {
  const mine = funcs.filter((f) => f.e === e);
  const all = (k) => [...new Set(mine.flatMap((f) => (Array.isArray(f[k]) ? f[k] : [])))];
  return { owners: all("owners"), reviewers: all("reviewers") };
};

/* ════════════════════════════════════════════════════════════════
   ПРОВЕРКИ СТРУКТУРЫ

   Три подписи на схеме — «актив», «функция», «ресурс» — белые, пока
   строение сходится, и красные, когда нет. Тексты ошибок даны владельцем
   дословно и здесь не пересказаны: это определения, по которым он строит
   модель, и вольный пересказ увёл бы смысл.

   Проверка структурная и от времени не зависит: она отвечает на вопрос
   «так ли собрано», а не «сколько сейчас чего». Поэтому ползунок времени
   на цвет подписи не влияет.

   Только что заведённый узел красный сразу — это и есть подсказка, что
   его надо достроить, а не поломка.

   Как устроены связи в этой модели: ребро идёт ОТ АКТИВА (`from`) К
   РЕСУРСУ (`to`) и может потреблять ресурс-источник (`fromTrait`).
   ════════════════════════════════════════════════════════════════ */

export const WHY_ASSET = "Актив — это то, что берёт один ресурс из внешней системы"
  + " и выдаёт другой. У него должна быть хотя бы одна стрелка, которая"
  + " показывает, откуда приходит внешний ресурс, и хотя бы одна стрелка,"
  + " которая показывает, куда уходит созданный.";

export const WHY_FUNC = "Функциональный элемент — это то, что преобразует внешний"
  + " ресурс во внутренний или наоборот. Тогда он является частью этого актива."
  + " Соответственно, либо все его стрелки внутри преобразуют один ресурс в"
  + " другой, либо его стрелки должны смотреть и наружу, и внутрь."
  + " Функция берёт несколько ресурсов и выдаёт несколько других, и у каждого"
  + " входа и выхода есть диапазон: сколько ресурса берётся и сколько выдаётся."
  + " Сначала диапазон закладывается, потом уточняется на реальных выполнениях —"
  + " по ним показывается среднее арифметическое. И у функции есть время, за"
  + " которое она выполняется.";

export const WHY_TRAIT = "Чтобы ресурс был задействован в активе, хотя бы одна"
  + " стрелка должна идти к нему и одна от него. Из них хотя бы одна стрелка"
  + " должна смотреть внутрь, чтобы ресурс считался ресурсом актива. И ресурс"
  + " не должен изменяться сам — это делают функциональные элементы.";

/** Актив: есть ли вход извне и выход наружу. */
export function checkAsset(id, { traits = [], edges = [] } = {}) {
  const own = new Set(traits.filter((t) => t.e === id).map((t) => t.id));
  const inside = edges.some((x) => own.has(x.to) && x.from !== id);
  const outside = edges.some((x) => x.from === id && !own.has(x.to));
  return { ok: inside && outside, why: WHY_ASSET };
}

/**
 * Ресурс: к нему идёт стрелка, от него идёт стрелка, хотя бы одна внутрь,
 * и сам себя он не меняет.
 *
 * «От него» считается мягко: не только явный расход (fromTrait) и не
 * только вход в функцию, но и стрелка, уходящая из его актива наружу.
 * Строгое чтение покрасило бы в день выката все ресурсы модели разом — а
 * красный, который горит везде, перестаёт что-либо значить.
 */
export function checkTrait(id, { traits = [], edges = [], funcs = [] } = {}) {
  const t = traits.find((x) => x.id === id);
  if (!t) return { ok: false, why: WHY_TRAIT };
  const own = new Set(traits.filter((x) => x.e === t.e).map((x) => x.id));

  const madeByFunc = funcs.some((f) => f.gives.some((g) => g.trait === id));
  const usedByFunc = funcs.some((f) => f.takes.some((k) => k.trait === id));

  const to = edges.some((x) => x.to === id) || madeByFunc;
  const from = edges.some((x) => x.fromTrait === id && x.to !== id)
    || usedByFunc
    || edges.some((x) => x.from === t.e && !own.has(x.to));
  // «Внутрь» — то, что приходит в актив: стрелка из другого актива либо
  // функция этого же актива, которая ресурс производит.
  const inward = edges.some((x) => x.to === id && x.from !== t.e)
    || funcs.some((f) => f.e === t.e && f.gives.some((g) => g.trait === id));
  const itself = edges.some((x) => x.to === id && x.fromTrait === id);

  return { ok: to && from && inward && !itself, why: WHY_TRAIT };
}

/**
 * Функция: либо преобразование целиком внутри актива, либо ресурсы и
 * наружу, и внутрь. Ничего не берущая или ничего не выдающая функция не
 * преобразует ничего — она тоже красная.
 *
 * Вилки и время проверяются здесь же, а не «потом при расчёте»: функция
 * без количества и без срока выглядит заполненной, но не говорит ни
 * сколько ресурса уйдёт, ни когда будет готово, — и в прогнозе окажется
 * невидимым нулём.
 */
export function checkFunc(f, { traits = [] } = {}) {
  if (!f || !f.takes?.length || !f.gives?.length) return { ok: false, why: WHY_FUNC };
  const ports = [...f.takes, ...f.gives];
  // Ссылка на удалённый ресурс — не «наружу», а обрыв: функция с ней не
  // преобразует ничего, и зелёной ей быть не за что.
  if (ports.some((p) => !traits.some((t) => t.id === p.trait))) return { ok: false, why: WHY_FUNC };
  if (ports.some((p) => !okRange(p))) return { ok: false, why: WHY_FUNC };
  if (hoursOf(f) <= 0) return { ok: false, why: WHY_FUNC };

  const own = new Set(traits.filter((t) => t.e === f.e).map((t) => t.id));
  const used = ports.map((p) => p.trait);
  const inner = used.filter((id) => own.has(id)).length;
  const outer = used.length - inner;
  return { ok: outer === 0 || (inner > 0 && outer > 0), why: WHY_FUNC };
}

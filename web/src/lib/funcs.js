/* ════════════════════════════════════════════════════════════════
   ФУНКЦИОНАЛЬНЫЕ ЭЛЕМЕНТЫ

   Ресурс — это то, что есть. Функциональный элемент — то, что его
   преобразует: берёт одни ресурсы и выдаёт другие, и на это уходит время.
   До сих пор преобразование жило прямо в стрелке между ресурсами, и
   поэтому его нельзя было ни поручить человеку, ни измерить: у стрелки
   нет ни ответственного, ни длительности, ни истории выполнения.

   Почему ОТДЕЛЬНЫЙ массив, а не ещё один вид ресурса. Ресурсы в этой
   модели — числа: они складываются, участвуют в целях, в условиях, в
   формулах, в подсказках, в прогнозе. Положив элемент к ним, мы получили
   бы «цель по функциональному элементу» и «долю от функционального
   элемента» в семи списках сразу. Элемент — не число, и путать их нельзя.

   ─── как устроена запись ───

   Элемент живёт внутри актива (`e`) и связан с ресурсами двумя списками:

   · takes — что берёт: [{trait, qty}]
   · gives — что выдаёт, и это ФУНКЦИИ элемента: у каждой свои
     длительность, ответственные и проверяющие. Владелец сказал прямо:
     «у каждого функционального элемента для разных функций, которыми они
     выдают ресурс, должны быть проверяющие», — значит функция это выход,
     а не элемент целиком.

   ─── про время ───

   `dur` — длительность ОДНОГО выполнения: «за какое время дизайнер
   сделает дизайн страницы». Не производительность за период. Из неё
   считается и срок задачи, и то, сколько выполнений помещается в шаг
   прогноза; а рядом копится факт — сколько вышло на самом деле.

   План показывается жёлтым, пока не выполнено ни одного цикла, и
   сменяется зелёным средним, когда циклы появились: пока факта нет,
   жёлтое число — обещание, а не измерение, и выдавать одно за другое
   нельзя.
   ════════════════════════════════════════════════════════════════ */

/** Единицы длительности. Значение — сколько в них часов. */
export const DUR_UNITS = { ч: 1, дн: 24, нед: 168, мес: 730 };
export const DUR_DEFAULT = "дн";

let seq = 0;
const nextId = (prefix) => {
  seq += 1;
  return `${prefix}${Date.now().toString(36)}${seq.toString(36)}`;
};

/** Одна функция элемента: что выдаёт, за сколько, кто делает и проверяет. */
export const newGive = (trait = "", qty = 1) => ({
  id: nextId("g"),
  trait,
  qty,
  dur: 1,
  durUnit: DUR_DEFAULT,
  owners: [],
  reviewers: [],
});

/** Новый функциональный элемент внутри актива. */
export const newFunc = (e, name = "новая функция") => ({
  id: nextId("f"),
  e,
  name,
  takes: [],
  gives: [],
  x: 0,
  y: 0,
});

/**
 * Приведение к нынешней записи.
 *
 * Сценарии и модели, сохранённые до появления элементов, поля funcs не
 * знают вовсе — там будет undefined, и это нормально. А вот запись,
 * пришедшую из чужого JSON, надо достроить: без списков takes/gives
 * редактор упадёт на первом же map, и человек увидит белый экран вместо
 * объяснения.
 */
export const normalizeFunc = (f) => ({
  ...f,
  e: f.e ?? null,
  name: f.name ?? "",
  takes: Array.isArray(f.takes) ? f.takes.map((t) => ({ trait: t.trait ?? "", qty: Number(t.qty) || 0 })) : [],
  gives: Array.isArray(f.gives) ? f.gives.map((g) => ({
    id: g.id ?? nextId("g"),
    trait: g.trait ?? "",
    qty: Number(g.qty) || 0,
    dur: Number(g.dur) || 0,
    durUnit: DUR_UNITS[g.durUnit] ? g.durUnit : DUR_DEFAULT,
    owners: Array.isArray(g.owners) ? g.owners : [],
    reviewers: Array.isArray(g.reviewers) ? g.reviewers : [],
  })) : [],
  x: Number(f.x) || 0,
  y: Number(f.y) || 0,
});

export const normalizeFuncs = (list) =>
  (Array.isArray(list) ? list.map(normalizeFunc) : []);

/** Длительность функции в часах — общая мера для сравнения и усреднения. */
export const hoursOf = ({ dur, durUnit } = {}) =>
  (Number(dur) || 0) * (DUR_UNITS[durUnit] ?? 1);

/** Обратно в удобные единицы: 36 часов — это «1.5 дн», а не «36 ч». */
export const fromHours = (h) => {
  const n = Number(h) || 0;
  const unit = ["мес", "нед", "дн", "ч"].find((u) => n >= DUR_UNITS[u]) || "ч";
  return { dur: Math.round((n / DUR_UNITS[unit]) * 10) / 10, durUnit: unit };
};

/**
 * Сколько выполнений функции помещается в один шаг прогноза.
 *
 * Шаг модели — месяц. Цикл короче месяца повторяется несколько раз; цикл
 * длиннее месяца выдаёт долю — иначе результат, на который ушло полгода,
 * появлялся бы разом и модель врала бы о сроках.
 */
export const cyclesPerMonth = (give) => {
  const h = hoursOf(give);
  return h > 0 ? DUR_UNITS["мес"] / h : 0;
};

/**
 * Среднее фактическое время цикла по выполненным задачам.
 *
 * Считается только по завершённым: незакрытая задача ничего не измеряет,
 * а взятая в расчёт занижала бы среднее ровно тогда, когда работа идёт.
 */
export const avgHours = (cycles = []) => {
  const done = cycles.filter((c) => Number(c) > 0);
  if (!done.length) return null;
  return done.reduce((s, c) => s + Number(c), 0) / done.length;
};

/* ════════════════════════════════════════════════════════════════
   ПРОВЕРКИ СТРУКТУРЫ

   Три подписи на схеме — «актив», «функциональный элемент», «ресурс» —
   белые, пока строение сходится, и красные, когда нет. Тексты ошибок
   даны владельцем дословно и здесь не пересказаны: это определения, по
   которым он строит модель, и вольный пересказ увёл бы смысл.

   Проверка структурная и от времени не зависит: она отвечает на вопрос
   «так ли собрано», а не «сколько сейчас чего». Поэтому ползунок времени
   на цвет подписи не влияет.

   Только что заведённый узел красный сразу — это и есть подсказка, что
   его надо достроить, а не поломка.

   Как устроены связи в этой модели: ребро идёт ОТ АКТИВА (`from`) К
   РЕСУРСУ (`to`) и может потреблять ресурс-источник (`fromTrait`).
   ════════════════════════════════════════════════════════════════ */

export const WHY_ASSET = "Актив — это то, что берёт один ресурс из внешней системы"
  + " и выдаёт другой. У него должна быть хотя бы одна стрелка, которая"
  + " показывает, откуда приходит внешний ресурс, и хотя бы одна стрелка,"
  + " которая показывает, куда уходит созданный.";

export const WHY_FUNC = "Функциональный элемент — это то, что преобразует внешний"
  + " ресурс во внутренний или наоборот. Тогда он является частью этого актива."
  + " Соответственно, либо все его стрелки внутри преобразуют один ресурс в"
  + " другой, либо его стрелки должны смотреть и наружу, и внутрь.";

export const WHY_TRAIT = "Чтобы ресурс был задействован в активе, хотя бы одна"
  + " стрелка должна идти к нему и одна от него. Из них хотя бы одна стрелка"
  + " должна смотреть внутрь, чтобы ресурс считался ресурсом актива. И ресурс"
  + " не должен изменяться сам — это делают функциональные элементы.";

/** Актив: есть ли вход извне и выход наружу. */
export function checkAsset(id, { traits = [], edges = [] } = {}) {
  const own = new Set(traits.filter((t) => t.e === id).map((t) => t.id));
  const inside = edges.some((x) => own.has(x.to) && x.from !== id);
  const outside = edges.some((x) => x.from === id && !own.has(x.to));
  return { ok: inside && outside, why: WHY_ASSET };
}

/**
 * Ресурс: к нему идёт стрелка, от него идёт стрелка, хотя бы одна внутрь,
 * и сам себя он не меняет.
 *
 * «От него» считается мягко: не только явный расход (fromTrait) и не
 * только вход в функциональный элемент, но и стрелка, уходящая из его
 * актива наружу. Строгое чтение покрасило бы в день выката все ресурсы
 * модели разом — а красный, который горит везде, перестаёт что-либо
 * значить.
 */
export function checkTrait(id, { traits = [], edges = [], funcs = [] } = {}) {
  const t = traits.find((x) => x.id === id);
  if (!t) return { ok: false, why: WHY_TRAIT };
  const own = new Set(traits.filter((x) => x.e === t.e).map((x) => x.id));

  const madeByFunc = funcs.some((f) => f.gives.some((g) => g.trait === id));
  const usedByFunc = funcs.some((f) => f.takes.some((k) => k.trait === id));

  const to = edges.some((x) => x.to === id) || madeByFunc;
  const from = edges.some((x) => x.fromTrait === id && x.to !== id)
    || usedByFunc
    || edges.some((x) => x.from === t.e && !own.has(x.to));
  // «Внутрь» — то, что приходит в актив: стрелка из другого актива либо
  // элемент этого же актива, который ресурс производит.
  const inward = edges.some((x) => x.to === id && x.from !== t.e)
    || funcs.some((f) => f.e === t.e && f.gives.some((g) => g.trait === id));
  const itself = edges.some((x) => x.to === id && x.fromTrait === id);

  return { ok: to && from && inward && !itself, why: WHY_TRAIT };
}

/**
 * Функциональный элемент: либо преобразование целиком внутри актива,
 * либо стрелки и наружу, и внутрь. Ничего не берущий или ничего не
 * выдающий элемент не преобразует ничего — он тоже красный.
 */
export function checkFunc(f, { traits = [] } = {}) {
  if (!f || !f.takes.length || !f.gives.length) return { ok: false, why: WHY_FUNC };
  const own = new Set(traits.filter((t) => t.e === f.e).map((t) => t.id));
  const used = [...f.takes.map((t) => t.trait), ...f.gives.map((g) => g.trait)];
  // Ссылка на удалённый ресурс — не «наружу», а обрыв: элемент с ней не
  // преобразует ничего, и зелёным ему быть не за что.
  if (used.some((id) => !traits.some((t) => t.id === id))) return { ok: false, why: WHY_FUNC };
  const inner = used.filter((id) => own.has(id)).length;
  const outer = used.length - inner;
  return { ok: outer === 0 || (inner > 0 && outer > 0), why: WHY_FUNC };
}

import { MODEL } from "./embedderWeights.js";

/* FNV-1a: короткий, ровно раскладывающий хеш. Номер строки — остаток от
   деления; коллизии неизбежны и не страшны — на них сеть и обучалась. */
function hash(text) {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i += 1) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

/* Признаки слова: куски из трёх букв (с границами, чтобы начало и конец
   слова считались) и само слово целиком — знакомое слово узнаётся им
   точнее, чем кусками. */
export function features(word) {
  const w = `·${word}·`;
  const out = [`#${word}`];
  for (let i = 0; i + 3 <= w.length; i += 1) out.push(w.slice(i, i + 3));
  return out;
}

/* Веса лежат в коде как байты: float32 раздул бы файл вчетверо, а
   точности сверх байта косинусу коротких слов не нужно. */
function decode(model) {
  const bin = typeof atob === "function"
    ? atob(model.data)
    : Buffer.from(model.data, "base64").toString("binary");
  const w = new Float32Array(model.buckets * model.dim);
  for (let i = 0; i < w.length; i += 1) {
    // Байты пишутся со сдвигом 128: так они укладываются в 0…255.
    w[i] = ((bin.charCodeAt(i) & 0xff) - 128) * model.scale;
  }
  return w;
}

let WEIGHTS = null;
export const weights = () => (WEIGHTS || (WEIGHTS = decode(MODEL)));
export const DIM = MODEL.dim;

const unit = (v) => {
  let n = 0;
  for (let i = 0; i < v.length; i += 1) n += v[i] * v[i];
  if (!n) return v;
  const k = 1 / Math.sqrt(n);
  for (let i = 0; i < v.length; i += 1) v[i] *= k;
  return v;
};

/** Вектор одного слова. */
export function wordVec(word, W = weights(), dim = DIM) {
  const v = new Float32Array(dim);
  for (const f of features(word)) {
    const row = (hash(f) % MODEL.buckets) * dim;
    for (let i = 0; i < dim; i += 1) v[i] += W[row + i];
  }
  return unit(v);
}

/** Вектор текста: среднее по словам. Длинное название не перевешивает. */
export function textVec(wordList, W = weights(), dim = DIM) {
  const v = new Float32Array(dim);
  if (!wordList.length) return v;
  for (const w of wordList) {
    const u = wordVec(w, W, dim);
    for (let i = 0; i < dim; i += 1) v[i] += u[i];
  }
  return unit(v);
}

/** Косинус двух векторов одной длины. */
export function dot(a, b) {
  let s = 0;
  for (let i = 0; i < a.length; i += 1) s += a[i] * b[i];
  return s;
}

/* ════════════════════════════════════════════════════════════════
   КЛАССИФИКАЦИИ РЕСУРСА

   Одна вещь бывает сразу нескольких видов: деньги — и ресурс, и затрата;
   заявка — и рост, и то, из чего делают работу. Пока классификация была
   одна, человеку приходилось выбирать, какой правдой пожертвовать, — и
   выбранная не отвечала на вопрос «а где остальное».

   Хранится списком (`ks`), а не полем: список из одного — это то же самое
   поле, а поле из списка не сделать, не потеряв остальные.

   Прежняя запись с одним `k` читается как список из одного. Переписывать
   сохранённые модели мы не станем: чтение мягкое, и старые схемы
   открываются как были.

   Классификация НИЧЕГО не считает — см. инвариант 9. Она говорит, чем
   человек считает эту вещь, и живёт только в показе: значок, цвет, имя.
   Поэтому список без единой классификации — не поломка, а «не сказано».
   ════════════════════════════════════════════════════════════════ */

const str = (v) => (v == null ? "" : String(v));

/** Какие классификации у ресурса. Старое поле `k` — список из одного. */
export function kindIdsOf(t = {}) {
  const list = Array.isArray(t.ks) ? t.ks : (t.k ? [t.k] : []);
  return [...new Set(list.map(str).filter(Boolean))];
}

/** Есть ли у ресурса такая классификация. */
export const hasKind = (t, id) => kindIdsOf(t).includes(str(id));

/**
 * Поставить или снять классификацию.
 *
 * Оба поля пишутся сразу: `ks` — правда, `k` — та же правда одним значением
 * для всего, что ещё читает старое поле (снимок для помощника, чужие
 * сценарии). Разъехаться они не могут: `k` всегда первый из `ks`.
 */
export function toggleKind(t = {}, id) {
  const key = str(id);
  if (!key) return t;
  const now = kindIdsOf(t);
  const next = now.includes(key) ? now.filter((x) => x !== key) : [...now, key];
  return { ...t, ks: next, k: next[0] || "" };
}

/** Убрать классификацию у всех ресурсов — её удалили из списка видов. */
export function dropKind(traits = [], id) {
  const key = str(id);
  return traits.map((t) => (kindIdsOf(t).includes(key) ? toggleKind(t, key) : t));
}

/** Сколько ресурсов ею помечено — нужно, чтобы сказать это вслух при удалении. */
export const countKind = (traits = [], id) =>
  traits.filter((t) => hasKind(t, id)).length;

/* ════════════════════════════════════════════════════════════════
   ПОИСК ПО СМЫСЛУ · лёгкая местная нейросеть (владелец, 2026-09-20)

   «Если у меня есть услуга „Разработка", а в поиск я ввожу
   „программирование", то этот поиск должен найти услугу по разработке».
   И: «если создать услугу „Тест" и ввести в поиск „тестировщик", то так
   не находит. Мне нужно, чтобы использовалась именно нейросеть, но
   лёгкая, локальная и чётко подходящая под эти задачи».

   Сравнивать надо не буквы, а смысл, и теперь это делает сеть, а не
   таблица весов: `lib/embedder.js` — обученный слой эмбеддингов над
   кусками слов, около сотни килобайт прямо в коде. Ни запроса в сеть, ни
   загрузки модели: поиск идёт на каждое нажатие клавиши, и ждать чужой
   ответ на каждую букву было бы не поиском.

   Что делает этот файл: разбирает текст на слова и основы (словарь и
   разбор — в `semanticGroups.js`), спрашивает у сети вектор и сравнивает
   косинусом. Порог отсекает случайное сходство: у обученной сети
   «разное» лежит около нуля, а «то же самое» — за 0,7, и между ними
   широкая пустота.

   Словарь понятий никуда не делся, но роль у него другая: раньше он
   отвечал на поиск, теперь — учит сеть (`tools/train-embedder.mjs`).
   Поэтому чего в нём нет, то всё равно ищется: сеть обобщает по кускам
   слов, и «тестировщик» находит «Тест», которого она не видела.
   ════════════════════════════════════════════════════════════════ */

import { dot, textVec, wordVec } from "./embedder.js";
import { GROUPS, conceptsOf, normalize, stem, words } from "./semanticGroups.js";

export { GROUPS, conceptsOf, normalize, stem, words };

/* Служебные слова: смысла у них нет, а в среднем они его размывают.
   «Доставка грузов по городу и области» — про доставку, а не про «по». */
const STOP = new Set(["и", "в", "на", "по", "с", "со", "для", "от", "до", "из",
  "не", "или", "а", "но", "к", "у", "о", "об", "за", "под", "при", "же", "бы",
  "что", "как", "это", "то", "ли", "мы", "вы", "я", "он", "она", "они"]);
const terms = (text) => words(text).filter((w) => !STOP.has(w));

/* ─── СРАВНЕНИЕ ПО СЛОВАМ, А НЕ ПО СРЕДНЕМУ ───

   Вектор всего текста — среднее по его словам, и у длинного текста смысл
   в нём тонет: «Доставка грузов по городу и области» отвечала «перевозке»
   0,37, хотя одно её слово — «грузов» — отвечает 0,85. Спрашивают ведь не
   «похож ли текст целиком», а «есть ли в нём то, что я ищу».

   Поэтому за каждое слово запроса берётся его ЛУЧШЕЕ совпадение среди
   слов записи, и они усредняются: запрос покрыт — значит нашли. Слов в
   названии единицы, так что перебор здесь дешевле, чем кажется, а
   векторы слов считаются один раз на запрос и один раз на запись. */
function coverage(qv, dv) {
  if (!qv.length || !dv.length) return 0;
  let sum = 0;
  for (const a of qv) {
    let best = -1;
    for (const b of dv) { const d = dot(a, b); if (d > best) best = d; }
    sum += best;
  }
  return sum / qv.length;
}

/** Векторы слов текста — то, чем его видит сеть. */
export const wordVecs = (text) => terms(text).map((w) => wordVec(w));

/** Вектор текста — то, чем его видит сеть.

   Основы (`stem`) здесь НЕ срезаются, хотя и остались наружу для других
   мест: сеть смотрит на куски слова и на падежи не ведётся сама, а
   обрезанное слово теряет свой признак «слово целиком» и получает
   ложную границу — «бухгалтер» превращается в «бухгалте», которого не
   бывает. Отрезать хвост перед тем, кто и так его понимает, — значит
   портить ему вход. */
export const vecOf = (text) => textVec(words(text));

/** Косинус между векторами: 0 — ничего общего, 1 — то же самое. */
export function cosine(a, b) {
  if (!a?.length || !b?.length) return 0;
  return dot(a, b);
}

/** Насколько близки два текста по смыслу. */
export const similarity = (a, b) => cosine(vecOf(a), vecOf(b));

/* Порог: ниже него совпадение — случайность, а не смысл. У обученной
   сети разные вещи лежат около нуля, поэтому порог стоит высоко: ему
   больше не нужно отделять смысл от общих букв — это сделала сеть. */
export const MIN_SCORE = 0.4;

const textOf = (item, fields) => fields.map((f) => item?.[f] || "").join(" ");

/**
 * Найти подходящее по смыслу.
 *
 * @param {string} query — что ввели
 * @param {object[]} items — среди чего искать
 * @param {{fields?: string[], limit?: number, min?: number}} opts
 * @returns {{item, score}[]} — от самого подходящего
 */
export function search(query, items = [], { fields = ["name", "text"], limit = 8,
  min = MIN_SCORE } = {}) {
  const q = wordVecs(query);
  if (!q.length) return [];
  return items
    .map((item) => ({ item, score: coverage(q, wordVecs(textOf(item, fields))) }))
    .filter((r) => r.score >= min)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit);
}

/** Ближайшие по смыслу к этому — без него самого. */
export function nearest(item, items = [], { fields = ["name", "text"], limit = 8,
  min = MIN_SCORE } = {}) {
  if (!item) return [];
  const base = wordVecs(textOf(item, fields));
  if (!base.length) return [];
  /* В обе стороны: «есть ли в соседе то, что есть здесь» и наоборот.
     Односторонняя мера объявила бы соседом любую запись, целиком
     вложенную в эту. */
  return items
    .filter((x) => x !== item && x?.id !== item?.id)
    .map((x) => {
      const v = wordVecs(textOf(x, fields));
      return { item: x, score: (coverage(base, v) + coverage(v, base)) / 2 };
    })
    .filter((r) => r.score >= min)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit);
}

/**
 * Готовые названия, близкие к набранному, — для подсказки в поле имени.
 * Повторы убираются: одно и то же название из двух записей — одна строка.
 */
export function nameHints(query, items = [], { limit = 6 } = {}) {
  const q = String(query || "").trim();
  if (q.length < 2) return [];
  const seen = new Set([normalize(q)]);
  const out = [];
  for (const { item, score } of search(q, items, { fields: ["name"], limit: limit * 3 })) {
    const name = String(item?.name || "").trim();
    const key = normalize(name);
    if (!name || seen.has(key)) continue;
    seen.add(key);
    out.push({ name, score });
    if (out.length >= limit) break;
  }
  return out;
}

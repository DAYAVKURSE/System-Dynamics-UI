/* Хвосты русских слов, которые не меняют смысл. Длинные сперва: иначе
   «разработка» потеряла бы только «а» и не совпала с «разработкой». */
const TAILS = ["иями", "ями", "ами", "иях", "ях", "ах", "ов", "ев", "ий", "ый", "ой",
  "ая", "ое", "ые", "ие", "ам", "ом", "ем", "ей", "ью", "ия", "ии", "и", "ы", "а", "о",
  "у", "е", "я", "ь", "й"];
const MIN_STEM = 4;

export const normalize = (text) => String(text || "")
  .toLowerCase().replace(/ё/g, "е")
  .replace(/[^\p{L}\p{N}]+/gu, " ")
  .trim();

/** Основа слова: срезаем известный хвост, если остаток ещё слово. */
export function stem(word) {
  const w = String(word || "");
  if (w.length <= MIN_STEM) return w;
  for (const t of TAILS) {
    if (w.length - t.length >= MIN_STEM && w.endsWith(t)) return w.slice(0, -t.length);
  }
  return w;
}

export const words = (text) => normalize(text).split(" ").filter((w) => w.length > 1);

/* Понятие слова: первая группа, чья основа стоит в начале этого слова.
   Сравниваем по началу, а не по равенству: в словаре лежат основы. */
const CONCEPTS = Object.entries(GROUPS);
export function conceptsOf(word) {
  const w = String(word || "");
  const out = [];
  for (const [id, list] of CONCEPTS) {
    if (list.some((root) => w.startsWith(root) || root.startsWith(w))) out.push(id);
  }
  return out;
}

const grams = (word) => {
  const w = `·${word}·`;
  const out = [];
  for (let i = 0; i + 3 <= w.length; i += 1) out.push(w.slice(i, i + 3));
  return out;
};

/* Веса слоёв: понятие важнее основы, основа важнее куска слова. Куски
   намеренно лёгкие: их у длинных слов много, и без этого «Доставка»
   перевешивала бы «Копирайтинг» у «Разработки» одними буквами. */
const W_CONCEPT = 3, W_STEM = 2, W_GRAM = 0.25;

/** Вектор текста — разреженная карта «признак → вес». */
export function vecOf(text) {
  const v = new Map();
  const add = (k, w) => v.set(k, (v.get(k) || 0) + w);
  for (const w of words(text)) {
    const s = stem(w);
    add(`s:${s}`, W_STEM);
    for (const c of conceptsOf(s)) add(`c:${c}`, W_CONCEPT);
    for (const g of grams(s)) add(`g:${g}`, W_GRAM);
  }
  return v;
}

/** Косинус между векторами: 0 — ничего общего, 1 — то же самое. */
export function cosine(a, b) {
  if (!a?.size || !b?.size) return 0;
  const [small, big] = a.size <= b.size ? [a, b] : [b, a];
  let dot = 0;
  for (const [k, w] of small) { const o = big.get(k); if (o) dot += w * o; }
  if (!dot) return 0;
  let na = 0, nb = 0;
  for (const w of a.values()) na += w * w;
  for (const w of b.values()) nb += w * w;
  return dot / Math.sqrt(na * nb);
}

/** Насколько близки два текста по смыслу. */
export const similarity = (a, b) => cosine(vecOf(a), vecOf(b));

/* Порог: ниже него совпадение — случайные общие буквы, а не смысл. */
export const MIN_SCORE = 0.15;

const textOf = (item, fields) => fields.map((f) => item?.[f] || "").join(" ");

/**
 * Найти подходящее по смыслу.
 *
 * @param {string} query — что ввели
 * @param {object[]} items — среди чего искать
 * @param {{fields?: string[], limit?: number, min?: number}} opts
 * @returns {{item, score}[]} — от самого подходящего
 */
export function search(query, items = [], { fields = ["name", "text"], limit = 8,
  min = MIN_SCORE } = {}) {
  const q = vecOf(query);
  if (!q.size) return [];
  return items
    .map((item) => ({ item, score: cosine(q, vecOf(textOf(item, fields))) }))
    .filter((r) => r.score >= min)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit);
}

/** Ближайшие по смыслу к этому — без него самого. */
export function nearest(item, items = [], { fields = ["name", "text"], limit = 8,
  min = MIN_SCORE } = {}) {
  if (!item) return [];
  const base = vecOf(textOf(item, fields));
  return items
    .filter((x) => x !== item && x?.id !== item?.id)
    .map((x) => ({ item: x, score: cosine(base, vecOf(textOf(x, fields))) }))
    .filter((r) => r.score >= min)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit);
}

/**
 * Готовые названия, близкие к набранному, — для подсказки в поле имени.
 * Повторы убираются: одно и то же название из двух записей — одна строка.
 */
export function nameHints(query, items = [], { limit = 6 } = {}) {
  const q = String(query || "").trim();
  if (q.length < 2) return [];
  const seen = new Set([normalize(q)]);
  const out = [];
  for (const { item, score } of search(q, items, { fields: ["name"], limit: limit * 3 })) {
    const name = String(item?.name || "").trim();
    const key = normalize(name);
    if (!name || seen.has(key)) continue;
    seen.add(key);
    out.push({ name, score });
    if (out.length >= limit) break;
  }
  return out;
}

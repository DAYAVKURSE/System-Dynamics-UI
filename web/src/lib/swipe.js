/** Какую долю ширины экрана должен пройти палец, чтобы это был свайп. */
export const SWIPE_SHARE = 0.4;

/**
 * Куда шагнуть по ряду вкладок: 1 — вправо, −1 — влево, 0 — не свайп.
 *
 * Движение поперёк (вниз или вверх дальше, чем вбок) — не свайп: человек
 * прокручивал страницу, а не менял вкладку.
 */
export function swipeStep({ dx = 0, dy = 0, width = 0, share = SWIPE_SHARE } = {}) {
  if (!(width > 0)) return 0;
  if (Math.abs(dx) < width * share) return 0;
  if (Math.abs(dx) <= Math.abs(dy)) return 0;
  return dx < 0 ? 1 : -1;
}

/**
 * Можно ли считать движение от этого места свайпом вкладок.
 *
 * Нельзя там, где движение пальца значит своё: карта и таймлайн
 * (`data-pannable`) возят содержимое, поля ввода выделяют текст.
 */
export function swipeFrom(el) {
  if (!el || typeof el.closest !== "function") return true;
  return !el.closest("[data-pannable],[data-noswipe],input,textarea,select,[contenteditable='true']");
}

/** Соседняя вкладка в ряду: за краем ряда вкладок нет — там и остаёмся. */
export function tabAfter(keys = [], cur, step = 0) {
  const i = keys.indexOf(cur);
  if (i < 0 || !step) return cur;
  const j = i + step;
  return j < 0 || j >= keys.length ? cur : keys[j];
}

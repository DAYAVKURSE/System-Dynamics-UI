/* ════════════════════════════════════════════════════════════════
   БАРАБАН ВКЛАДОК (владелец, 2026-09-21, третий заход)

   «Всё равно не выглядит как круглый барабан: слова уменьшаются целиком,
   а не плавно, не видно изгиб. Движение должно происходить плавно, с
   небольшой задержкой и самую малость прерывисто — как будто внутри много
   шестерёнок, участвующих в движении тяжёлого барабана. Линза должна
   немного увеличивать 60% площади объекта посередине и плавно
   расплываться к краям, как реальная линза на радиоприёмнике».

   Три вещи, и у каждой своя формула:

   · ЦИЛИНДР — настоящий, а не «повернуть вкладку целиком». Каждая БУКВА
     стоит на своём месте дуги: угол — длина дуги, делённая на радиус;
     буква сдвигается к проекции R·sin θ, уходит вглубь на R·(1−cos θ) и
     поворачивается на θ. Одна перспектива на всё окно, поэтому изгиб
     виден внутри слова: буквы у обода сжимаются сильнее, чем у середины
     того же слова.

   · ЛИНЗА — плоская посередине и гаснущая к краям: exp(−(t/W)⁴). Больше
     половины своего увеличения она держит на ~60 % ширины окна, а дальше
     сходит на нет без единого излома. «Немного» — GROW.

   · ХОД — тяжёлый: положение не равно цели, а догоняет её со скоростью,
     которую гасит трение (LAG, DAMP) — отсюда задержка. Поверх — зубья:
     пока барабан движется, к положению подмешивается синус с шагом TOOTH
     и амплитудой, растущей со скоростью, — на глаз ход чуть
     прерывистый, как у механизма. Остановился — зубьев нет, и барабан
     стоит ровно на цели.

   Здесь только счёт, без DOM.
   ════════════════════════════════════════════════════════════════ */

/** Промежуток между вкладками. */
export const GAP = 8;
/** Ширина вкладки и окна, когда мерить нечем (тест без разметки). */
export const NOMINAL_W = 96;
export const NOMINAL_WIN = 240;

/** Расстояние до глаза, px. */
export const EYE = 620;
/** Радиус барабана — в половинах окна: чем больше, тем площе. */
export const CURVE = 1.15;
/** Насколько крупнее посередине — «немного». */
export const GROW = 0.12;
/** Ширина плоской части линзы: половина увеличения держится до ~0.6. */
export const LENS_W = 0.66;
/** Насколько гаснет буква, ушедшая на обод. */
export const DIM = 0.3;

/** Тяжесть хода: доля разрыва, добираемая за кадр, и трение. Подобраны
    так, чтобы ход был критически затухающим — тяжёлый барабан, а не
    пружина: (1 − LAG + DAMP)² ≥ 4·DAMP, и перелёта нет. */
export const LAG = 0.05;
export const DAMP = 0.6;
/** Зубья: шаг, px, и глубина прикуса, px. */
export const TOOTH = 9;
export const BITE = 1.1;

const clamp = (x, a, b) => Math.max(a, Math.min(b, x));

/** Центры вкладок в ряду по их ширинам. */
export function centers(widths = [], gap = GAP) {
  const out = [];
  let x = 0;
  for (const w of widths) { out.push(x + w / 2); x += w + gap; }
  return out;
}

/** Номер вкладки, ближайшей к середине окна. */
export function nearest(cs = [], offset = 0) {
  let best = -1;
  let far = Infinity;
  cs.forEach((c, i) => { const d = Math.abs(c - offset); if (d < far) { far = d; best = i; } });
  return best;
}

/** Дальше первой и последней вкладки барабан не крутится. */
export function hold(cs = [], offset = 0) {
  if (!cs.length) return 0;
  return clamp(offset, cs[0], cs[cs.length - 1]);
}

/** Радиус барабана по половине окна. */
export const radiusOf = (half) => CURVE * Math.max(1, half);

/**
 * Куда встаёт точка ряда, стоящая в `x` px от середины окна по дуге.
 * `dx` — на сколько её сдвинуть от места в разметке, `dz` — вглубь,
 * `th` — угол; `hidden` — ушла за обод (дальше четверти оборота).
 */
export function bend(x, R) {
  const th = x / R;
  if (Math.abs(th) >= Math.PI / 2) {
    return { dx: (th < 0 ? -R : R) - x, dz: -R, th: clamp(th, -Math.PI / 2, Math.PI / 2), hidden: true };
  }
  return { dx: R * Math.sin(th) - x, dz: 0 - R * (1 - Math.cos(th)), th, hidden: false };
}

/** Во сколько раз линза увеличивает то, что стоит в `u` (−1…1) от середины. */
export function lens(u) {
  const t = clamp(Math.abs(Number(u) || 0), 0, 1);
  return 1 + GROW * Math.exp(-((t / LENS_W) ** 4));
}

/** Насколько видна буква под углом `th` к глазу. */
export function dimAt(th) {
  const c = Math.cos(clamp(Math.abs(th), 0, Math.PI / 2));
  return DIM + (1 - DIM) * c ** 1.5;
}

/** Один кадр тяжёлого хода: положение и скорость. */
export function step({ at = 0, v = 0 } = {}, aim = 0) {
  const nv = v * DAMP + (aim - at) * LAG;
  return { at: at + nv, v: nv };
}

/** Где барабан ВИДЕН: положение плюс зубья, растущие со скоростью. */
export function shown(at, v) {
  const s = Math.min(1, Math.abs(v) / 2.5);
  return at + BITE * s * Math.sin((2 * Math.PI * at) / TOOTH);
}

/** Доехал ли: и разрыв, и скорость уже неразличимы. */
export const settled = ({ at = 0, v = 0 } = {}, aim = 0) =>
  Math.abs(aim - at) < 0.05 && Math.abs(v) < 0.02;

/** Угол в градусах для стиля. */
export const deg = (th) => ((th * 180) / Math.PI).toFixed(2);

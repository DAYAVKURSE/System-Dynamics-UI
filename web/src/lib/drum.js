/* ════════════════════════════════════════════════════════════════
   БАРАБАН ВКЛАДОК (владелец, 2026-09-21)

   «Должен быть эффект увеличения: объекты уменьшаются к краю и
   увеличиваются посередине ПЛАВНО. Сейчас это выглядит так, как будто
   барабан многоугольный»; «активной вкладкой должна становиться та,
   которая в середине, а не та, на которую нажали. Барабан не должен
   реагировать на нажатие»; «в конце анимации объекты резко двигаются
   вправо на несколько пикселей».

   Все три беды были из одного корня. Барабан ехал НАТИВНОЙ прокруткой, а
   вид вкладок пересчитывался по событию `scroll`. События приходят реже
   кадров, увеличение считалось кусочной формулой с порогами — и
   получалось ровно то, на что жалуются: между порогами вкладка не
   менялась вовсе, у порога менялась рывком (грани многоугольника), а
   последний, самый большой, скачок приходился на конец прокрутки, когда
   ряд уже стоял.

   Поэтому барабан больше не прокручивается браузером. Положение — одно
   число `offset`: сколько пикселей ряда левее середины окна. Его ведём
   мы сами, кадр за кадром, и по нему же считаем вид. Здесь — только счёт:
   ширины, центры, ближайшая вкладка и сама линза. Без DOM, и потому
   проверяется числами.
   ════════════════════════════════════════════════════════════════ */

/** Промежуток между вкладками — тот же, что был у ряда. */
export const GAP = 8;
/** Ширина вкладки, когда мерить нечем (тест без разметки). */
export const NOMINAL_W = 96;
/** Ширина окна барабана на тот же случай. */
export const NOMINAL_WIN = 240;

/** Самая крупная вкладка — та, что посередине. */
export const BIG = 1.18;
/** Самая мелкая — у самого края. */
export const SMALL = 0.62;
/** На сколько градусов вкладка у края повёрнута к нам ребром. */
export const TURN = 34;
/** На сколько она уходит вглубь. */
export const DEPTH = 22;
/** Насколько гаснет у края. */
export const DIM = 0.4;
/** Расстояние до глаза. */
export const EYE = 360;

const clamp = (x, a, b) => Math.max(a, Math.min(b, x));

/** Центры вкладок в ряду по их ширинам. */
export function centers(widths = [], gap = GAP) {
  const out = [];
  let x = 0;
  for (const w of widths) { out.push(x + w / 2); x += w + gap; }
  return out;
}

/** Номер вкладки, ближайшей к середине окна. */
export function nearest(cs = [], offset = 0) {
  let best = 0;
  let far = Infinity;
  cs.forEach((c, i) => { const d = Math.abs(c - offset); if (d < far) { far = d; best = i; } });
  return cs.length ? best : -1;
}

/** Дальше первой и последней вкладки барабан не крутится. */
export function hold(cs = [], offset = 0) {
  if (!cs.length) return 0;
  return clamp(offset, cs[0], cs[cs.length - 1]);
}

/**
 * Как выглядит вкладка, стоящая в `u` от середины окна.
 *
 * Увеличение — колокол cos²: единица посередине, ноль у края, и в обеих
 * точках производная нулевая. Поэтому нигде нет излома: вкладка растёт и
 * убывает ПЛАВНО, а не ступенями с порогами.
 *
 * Поворот — прямо пропорционален месту. Это и есть цилиндр: у барабана
 * угол набегает вместе с дугой, равномерно. Прежний квадрат после порога
 * и делал из барабана многоугольник — вкладки стояли гранями.
 *
 * @param {number} u -1 — левый край окна, 0 — середина, +1 — правый.
 */
export function lensAt(u) {
  const x = clamp(Number.isFinite(Number(u)) ? Number(u) : 0, -1, 1);
  const bell = Math.cos((Math.abs(x) * Math.PI) / 2) ** 2;
  const turn = x * TURN;
  return {
    scale: SMALL + (BIG - SMALL) * bell,
    turn,
    depth: -DEPTH * (1 - Math.cos((turn * Math.PI) / 180)),
    dim: DIM + (1 - DIM) * bell,
  };
}

/** То же самое стилем — ровно то, что кладётся вкладке. */
export function lensStyle(u) {
  const l = lensAt(u);
  return {
    transform: `perspective(${EYE}px) rotateY(${l.turn.toFixed(2)}deg)`
      + ` translateZ(${l.depth.toFixed(2)}px) scale(${l.scale.toFixed(3)})`,
    opacity: l.dim.toFixed(3),
  };
}

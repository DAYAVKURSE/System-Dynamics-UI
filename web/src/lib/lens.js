/* ════════════════════════════════════════════════════════════════
   ЛУПА НА РЯДУ ВКЛАДОК (владелец, 2026-09-21)

   «Сделай на вкладках эффект вытянутой горизонтально лупы, чтобы объект
   находящийся в середине был увеличен, а объекты по краям уменьшались, но
   только прямо близко к краю, чтобы это действительно выглядело как
   увеличительное стекло, например, на счётчике, а текст как будто написан
   на крутящемся внутри цилиндре».

   Отсюда три требования, и каждое — своя часть формулы:

   · УВЕЛИЧЕНИЕ достаёт недалеко от середины: за `REACH` (треть половины
     ряда) его уже нет. Иначе увеличенными оказались бы все вкладки разом,
     и лупы не видно — видно просто крупный шрифт.
   · УМЕНЬШЕНИЕ начинается не раньше `EDGE` — «только прямо близко к
     краю». Между `REACH` и `EDGE` вкладка обычного размера: это стекло
     плоское по середине и загнутое по ободу.
   · ЦИЛИНДР — это поворот вокруг вертикальной оси и уход вглубь: у самого
     края вкладка встаёт ребром, как надпись на барабане счётчика,
     уезжающая за его обвод. Поворот растёт квадратом — у обода резко, а
     не полого.

   Здесь только счёт, без DOM: положение вкладки приходит числом от -1
   (левый край ряда) до +1 (правый), и тем же числом проверяется.
   ════════════════════════════════════════════════════════════════ */

/** Докуда достаёт увеличение — в долях половины ряда. */
export const REACH = 0.34;
/** Где начинается обод: ближе к середине вкладка не уменьшается вовсе. */
export const EDGE = 0.62;
/** Насколько крупнее вкладка в самой середине. */
export const GROW = 0.18;
/** Насколько вкладка у края встаёт ребром, в градусах. */
export const TURN = 74;
/** Насколько она же уходит вглубь, в пикселях. */
export const DEPTH = 30;
/** Расстояние до глаза: чем меньше, тем резче заворот. */
export const EYE = 320;

/* Сглаживание: без него увеличение нарастало бы уголком, и «стекло»
   выглядело бы склеенным из двух прямых. */
const smooth = (x) => x * x * (3 - 2 * x);

/**
 * Что делать с вкладкой, которая стоит в `u` от середины ряда.
 * @param {number} u -1 — левый край, 0 — середина, +1 — правый край.
 */
export function lensAt(u) {
  const x = Number.isFinite(Number(u)) ? Math.max(-1, Math.min(1, Number(u))) : 0;
  const t = Math.abs(x);
  const grow = t >= REACH ? 0 : smooth(1 - t / REACH);
  const k = t <= EDGE ? 0 : (t - EDGE) / (1 - EDGE);
  /* Квадрат, а не сама доля: у обода заворот должен нарастать резко —
     иначе «близко к краю» растягивается на треть ряда. */
  const roll = k * k;
  return {
    scale: 1 + GROW * grow - 0.06 * roll,
    turn: (x < 0 ? -1 : 1) * TURN * roll,
    depth: -DEPTH * roll,
    dim: 1 - 0.45 * roll,
  };
}

/** То же самое, но уже стилем: ровно то, что кладётся вкладке. */
export function lensStyle(u) {
  const l = lensAt(u);
  return {
    transform: `perspective(${EYE}px) rotateY(${l.turn.toFixed(2)}deg)`
      + ` translateZ(${l.depth.toFixed(2)}px) scale(${l.scale.toFixed(3)})`,
    opacity: l.dim.toFixed(3),
  };
}

/**
 * Где стоит вкладка в ряду: -1..+1 от середины видимой части.
 * Считается по разметке (`offsetLeft`), а не по `getBoundingClientRect`:
 * прямоугольник на экране УЖЕ повёрнут и уменьшен нами самими, и мерить
 * по нему значило бы кормить формулу её же ответом.
 */
export function placeIn(box, el) {
  const half = (box?.clientWidth || 0) / 2;
  if (!half) return 0;
  const mid = (el.offsetLeft || 0) + (el.offsetWidth || 0) / 2 - (box.scrollLeft || 0);
  return Math.max(-1, Math.min(1, (mid - half) / half));
}

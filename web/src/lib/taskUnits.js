/* ════════════════════════════════════════════════════════════════
   МАТЕРИАЛЫ ЗАДАЧИ · что лежит на входе и что вышло из сдачи

   Исполнителю, который открыл задачу, нужны не числа «спрос 4», а сами
   вещи: вот эта заявка, вот этот договор — их и скачивают, чтобы работать.
   Проверяющему нужно то же с другой стороны: что взяли и что выдали,
   вещами, а не количеством, — принимают работу по тому, что вышло.

   Оба вопроса отвечаются одним списком единиц (`unitsOf`), и правила
   здесь только про то, какие строки из него кому показать. Второго
   способа считать «что на входе» быть не должно: разойдись он с тем, что
   исполнитель отмечает как «взял» при сдаче, форма показывала бы одно, а
   записывала другое.
   ════════════════════════════════════════════════════════════════ */
import { spentIds, unitsOf } from "./units.js";

/**
 * Единицы на входе функции — по каждому входу свои, и только те, что ещё
 * не израсходованы.
 *
 * Израсходованная единица — не вход: её больше нет ни у кого, и показать
 * её значило бы предложить работать с тем, чего нет. Непринятые сдачи не
 * прячутся — так же, как и при выборе «взял»: человек уже сдал эту вещь,
 * и следующий видит, что она есть, хоть и не принята.
 */
export function inputUnits(model = {}, func = null) {
  const units = unitsOf(model);
  const spent = spentIds(model);
  return (func?.takes || []).map((p) => ({
    trait: p.trait,
    units: units.filter((u) => u.trait === p.trait && !spent.has(u.id)),
  }));
}

/** Сколько всего единиц лежит на входе — число для узкой карточки. */
export const inputCount = (model = {}, func = null) =>
  inputUnits(model, func).reduce((n, g) => n + g.units.length, 0);

/**
 * Что взято в этой сдаче — единицы по номерам, которые назвал исполнитель.
 *
 * Не назвал — списка нет, и достраивать его по количествам нельзя: вышла
 * бы догадка с видом знания. Тогда остаётся только количество (`takes`),
 * и его показывают словами «какие именно — не названо».
 */
export function tookUnits(units = [], sb = null) {
  const ids = [...new Set(Object.values(sb?.took || {}).flat().filter(Boolean))];
  return ids.map((id) => units.find((u) => u.id === id)).filter(Boolean);
}

/**
 * Что выдано этой сдачей — строки, которые из неё развернул `unitsOf`.
 *
 * Строки есть только у последней сдачи: результат задачи — это то, что
 * сдали в последний раз, и вещи прежних сдач в число единиц не входят.
 */
export const givenUnits = (units = [], task = null, sb = null) =>
  units.filter((u) => u.task === task?.id && u.sub === sb?.id);

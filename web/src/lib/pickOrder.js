import { byCrew } from "./funcs.js";

/* ПОРЯДОК ВОРКЕРОВ ПРИ ВЫБОРЕ.

   Список воркеров актива владелец выстраивает руками, и по умолчанию этот
   порядок ЗНАЧИТ: кого поставили выше, того берут первым — в форме
   постановки он стоит первым в выборе и подставляется сам, пока поле пусто.
   Так владелец, не заходя в каждую задачу, решает, на кого работа ложится
   в первую очередь.

   Выключается галочкой под списком (`entities[].pickByOrder`): тогда
   порядок в списке — просто порядок, воркеров предлагают по алфавиту и
   никого не подставляют. Отсутствующее поле читается как «включено»:
   этого поведения владелец и хотел, а галочка — чтобы от него отказаться,
   а не чтобы на него согласиться; старые записи ничего не теряют. */

/** Влияет ли положение в списке воркеров на выбор: нет только явного «нет». */
export const pickByOrderOf = (asset) => asset?.pickByOrder !== false;

/**
 * Воркеры в том порядке, в каком их предлагать: по списку актива или по
 * имени. Алфавит — потому что при выключенном порядке никакого «первого»
 * быть не должно, а случайный порядок читался бы как чей-то выбор.
 */
export const pickOrder = (asset, people = []) => (pickByOrderOf(asset)
  ? byCrew(asset || {}, people)
  : [...people].sort((a, b) => String(a?.name ?? a?.id ?? a)
    .localeCompare(String(b?.name ?? b?.id ?? b), "ru")));

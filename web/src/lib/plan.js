/* ════════════════════════════════════════════════════════════════
   РАСЧЁТ ПО ФУНКЦИЯМ

   Прежний расчёт шёл по стрелкам «актив → ресурс»: у стрелки была
   интенсивность, период, знак и условия, а работа человека к ней не
   относилась никак. Его больше нет. Считает теперь то, что и делает дело:
   функции.

   ─── откуда берутся числа ───

   У функции есть время одного выполнения. За месяц она выполняется
   столько раз, сколько раз это время в месяц помещается: цикл в неделю —
   примерно четыре раза, цикл в полгода — одна шестая раза (результат,
   на который ушло полгода, не может появиться разом).

   На каждом выполнении функция берёт свои входы и выдаёт свои выходы — в
   пределах заложенной вилки. Отсюда и весь прогноз: уровень ресурса это
   его начальное значение плюс всё, что функции в него выдали, минус всё,
   что они из него взяли.

   ─── почему прогноз — это лента, а не линия ───

   Вилка входа и выхода — гипотеза. Значит и уровень ресурса не число, а
   промежуток:

   · нижняя граница — выдали по минимуму, взяли по максимуму;
   · верхняя — выдали по максимуму, взяли по минимуму.

   Одна линия здесь была бы обманом: она выглядела бы как знание, которого
   нет. Когда появляются фактические выполнения, рядом с лентой встаёт
   линия факта — по среднему арифметическому того, что вышло на самом деле.

   ─── чего не хватает, того не берут ───

   Функция не может взять больше, чем есть: ресурс не уходит в минус. Если
   за месяц спрос на ресурс больше остатка, все, кто его берёт, получают
   поровну — по своей доле спроса. Это не «кто раньше встал», потому что
   порядок функций в списке — случайность заведения, а не приоритет, и
   расчёт не должен от него зависеть.

   ─── чего расчёт НЕ делает ───

   Число исполнителей на скорость не влияет. Владелец описал исполнителей
   как тех, кто функцию выполняет и отвечает за неё, а не как множитель
   производительности; домножать на количество людей значило бы додумать
   за него, что двое делают вдвое быстрее.
   ════════════════════════════════════════════════════════════════ */
import { CHANCE_MAX, DUR_UNITS, factorChance, factorsOf, everyOf, groupsOf, hoursOf, isFactor,
  portSpends, runHours, runQty } from "./funcs.js";

/** Часов в месяце — шаг модели. */
export const MONTH_H = DUR_UNITS["мес"];

/** Стороны прогноза: осторожная, щедрая и фактическая. */
export const SIDES = ["lo", "hi", "fact"];

const num = (v) => Number(v) || 0;

/**
 * Сколько времени занимает одно выполнение с учётом расписания.
 *
 * Расписание не ускоряет работу и не заменяет её: функция, которая делается
 * час, но повторяется раз в месяц, занимает месяц на цикл. Поэтому берётся
 * большее из двух — работа и пауза до следующего раза.
 */
export function stepHours(f, runs = [], side) {
  /* Сторона разводится так же, как у ресурсов: щедрая оценка берёт быструю
     работу, осторожная — долгую. Факт, когда он есть, вытесняет вилку
     целиком: измеренное не нуждается в границах. */
  const plan = side === "hi" ? hoursOf(f, "lo") : side === "lo" ? hoursOf(f, "hi") : hoursOf(f);
  const work = runHours(runs) ?? plan;
  return Math.max(work, everyOf(f, side));
}

/**
 * Сколько раз функция МОЖЕТ выполниться за месяц — её потолок.
 *
 * Это ёмкость, а не расписание. Сама по себе функция не повторяется: она
 * работа, и происходит тогда, когда её делают. Раньше это число означало
 * «столько раз она и выполнится», и прогноз крутил всю модель на полную
 * мощность вечно — показывая будущее, которого никто не планировал.
 *
 * По факту, если он есть: реальное время цикла честнее заложенного. Ноль
 * времени — не бесконечность, а «не считаем»: функция без срока ничего не
 * говорит о том, когда будет готово.
 */
export function cycles(f, runs = [], side) {
  const h = stepHours(f, runs, side);
  return h > 0 ? MONTH_H / h : 0;
}

/**
 * Сколько ресурса берёт (или выдаёт) порт на одном выполнении.
 *
 * Для нижней границы уровня берут по максимуму и выдают по минимуму, для
 * верхней — наоборот. Факт, когда он есть, вытесняет вилку с обеих сторон:
 * измеренное не нуждается в границах.
 */
export function portQty(p, { kind, side, runs = [] }) {
  const fact = runQty(runs, kind, p.trait);
  if (side === "fact" || fact != null) return fact ?? (num(p.lo) + num(p.hi)) / 2;
  const lo = num(p.lo);
  const hi = num(p.hi);
  const worst = kind === "takes" ? hi : lo;
  const best = kind === "takes" ? lo : hi;
  return side === "lo" ? worst : best;
}

/* ─────── жребий: удалась попытка или нет ───────

   Фактор случается сам, и «сам» не значит «наверняка»: у него есть
   вероятность, и каждая попытка — отдельный жребий. Поэтому один и тот же
   набор чисел может развиться по-разному, и посмотреть на эти варианты —
   ровно то, ради чего вероятность и заводят.

   Жребий не настоящий, а посеянный: от одного и того же семени выходит
   один и тот же ряд. Без этого прогноз менялся бы при каждой перерисовке —
   подвинул мышь, и другое будущее; сравнить два варианта стало бы
   невозможно, потому что не осталось бы ни одного, который стоит на месте.
   Меняя семя, человек смотрит следующий вариант. */
const hash = (s) => {
  let h = 2166136261;
  for (let i = 0; i < s.length; i += 1) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
};

/** Число в [0;1) по семени и месту: одно и то же место даёт одно и то же. */
export const draw = (seed, key) => {
  let x = hash(`${seed}|${key}`) || 1;
  x ^= x << 13; x >>>= 0;
  x ^= x >> 17;
  x ^= x << 5; x >>>= 0;
  return x / 4294967296;
};

/**
 * Удалась ли одна попытка фактора.
 *
 * Факторов у функции бывает несколько, и это просто СПИСОК: за попытку
 * функция пробует применить первый; вышло — попытка удалась и до второго
 * дело не доходит. Не вышло — пробует второй, потом третий, и так до конца
 * списка. Не удался ни один — не случилось ничего.
 *
 * Не «должны случиться все»: запасной вариант обязан помогать, а не мешать.
 * От «всех сразу» цепочка выходила бы тем реже, чем больше у неё запасных
 * путей, — то есть каждый добавленный фактор ухудшал бы дело.
 *
 * Жребий на каждый фактор — свой и посеянный, как и прежде: от одного
 * семени выходит один и тот же ряд, и обе стороны ленты говорят об одном
 * и том же варианте будущего.
 */
export function factorHit(f, factors = [], seed = 1, key = "") {
  const ids = factorsOf(f);
  if (!ids.length) return draw(seed, key) < 1;
  return ids.some((id, i) => {
    const x = factors.find((y) => y.id === id);
    return draw(seed, `${key}@${i}:${id}`) < factorChance(x) / CHANCE_MAX;
  });
}

/**
 * Какой из вариантов группы «или» пойдёт в дело.
 *
 * Берётся тот, которого хватает НА ДОЛЬШЕ: не «чего больше в штуках», а
 * чего больше относительно того, сколько его нужно. Сто единиц при нужде в
 * пятьдесят — это два выполнения, десять при нужде в одну — десять; первое
 * выглядит богаче, а второе богаче на самом деле.
 *
 * Ничего нет вовсе — берём первый по списку: порядок вариантов человек
 * задаёт сам, и это его предпочтение. Выбор обязан быть один и тот же при
 * каждом пересчёте, иначе прогноз прыгал бы от перерисовки к перерисовке.
 */
export function pickAlt(group, { have, kind = "takes", side, runs }) {
  if (group.length < 2) return group[0];
  let best = group[0];
  let bestCover = -1;
  group.forEach((p) => {
    const need = portQty(p, { kind, side, runs });
    if (!(need > 0)) return;
    /* Вторым доводом идёт сам порт: у входа, который не расходует, своё
       «сколько доступно» — то, чего эта функция ещё не обрабатывала. */
    const cover = (have(p.trait, p) || 0) / need;
    if (cover > bestCover) { bestCover = cover; best = p; }
  });
  return bestCover > 0 ? best : group[0];
}

/** Входы функции после выбора вариантов: по одному из каждой группы «или». */
export const takesOf = (f, opts) =>
  groupsOf(f.takes).map((g) => pickAlt(g, opts)).filter(Boolean);

/** Есть ли у функции хоть одно фактическое выполнение. */
export const hasFact = (runs = []) => runs.some((r) => Number(r?.hours) > 0);

/**
 * Прогон модели по месяцам — одна сторона прогноза.
 *
 * Возвращает по ряду значений на каждый ресурс: значение на конец каждого
 * месяца, начиная с нулевого (то, что есть сейчас).
 *
 * ─── откуда берутся выполнения ───
 *
 * Из применённых целей, а не из самих функций. Функция — это работа, и сама
 * по себе она не повторяется; «как часто может повторяться» — её потолок, а
 * не расписание. Прежде прогноз крутил каждую функцию на полную мощность
 * вечно и показывал будущее, которого никто не планировал: числа росли сами
 * собой, и цель в них ничего не меняла.
 *
 * `plan` — что требуют цели: `perMonth` повторяется каждый месяц (цель с
 * темпом), `once` — разовый запас работы, который тратится, пока не
 * кончится. Плана нет вовсе — считаем по потолку: так прогноз отвечает на
 * вопрос «на что модель вообще способна».
 */
export function runSide(model, { span = 24, side = "hi", runsOf, plan, seed = 1 } = {}) {
  const { traits = [], funcs = [], factors = [] } = model;
  const runs = (f) => (runsOf ? runsOf(f.id) : []);
  /* Недобранные попытки копятся: фактор с попыткой раз в полгода делает
     одну попытку раз в шесть месяцев, а не шестую часть попытки каждый
     месяц. Половины жребия не бывает. */
  const credit = {};
  const tries = {};
  const perMonth = plan?.perMonth || {};
  const left = { ...(plan?.once || {}) };
  const level = {};
  const out = {};
  traits.forEach((t) => { level[t.id] = num(t.have); out[t.id] = [level[t.id]]; });

  /* Сколько единиц ресурса функция уже ОБРАБОТАЛА, не расходуя.
     Обработанное лежит на месте и достаётся другим функциям — но этой
     второй раз не даётся: работа по нему уже сделана. Ключ — функция и
     ресурс вместе: ограничение принадлежит одной функции, а не всем. */
  const seen = {};
  const seenKey = (f, p) => `${f.id}|${p.trait}`;
  const fresh = (f, p) => (portSpends(p)
    ? (level[p.trait] ?? 0)
    : Math.max(0, (level[p.trait] ?? 0) - (seen[seenKey(f, p)] || 0)));

  for (let m = 0; m < span; m += 1) {
    const wave = funcs.map((f) => {
      // Потолок — сколько попыток вообще помещается в месяц.
      const cap = cycles(f, runs(f), side);
      /* Фактор случается сам: его не просят и не назначают, он идёт своим
         чередом — столько попыток, сколько помещается, и из них удаются те,
         на которые хватило вероятности. Задача — наоборот: её делают, и
         делают ровно столько, сколько просят применённые цели. */
      if (isFactor(f)) {
        credit[f.id] = (credit[f.id] || 0) + cap;
        let hit = 0;
        while (credit[f.id] >= 1) {
          credit[f.id] -= 1;
          tries[f.id] = (tries[f.id] || 0) + 1;
          if (factorHit(f, factors, seed, `${f.id}#${tries[f.id]}`)) hit += 1;
        }
        return { f, n: hit, k: 1, takes: [] };
      }
      const want = perMonth[f.id] || 0;
      const budget = left[f.id] || 0;
      const n = plan ? Math.min(cap, want + budget) : cap;
      // Разовый запас тратится тем, что сделано сверх повторяющегося.
      if (plan) left[f.id] = Math.max(0, budget - Math.max(0, n - want));
      return { f, n, k: 1, takes: [] };
    });

    // Спрос на каждый ресурс за месяц — и доля, которая на самом деле
    // достанется, если спрос больше остатка.
    /* Что именно берёт функция, решается ЗДЕСЬ, до подсчёта спроса: в
       группе «или» вариант выбирается по остатку на начало месяца. Дальше
       функция работает уже с выбранным — иначе спрос считался бы по одному
       ресурсу, а списывался другой. */
    wave.forEach((w) => {
      w.takes = takesOf(w.f, { have: (id, p) => (p ? fresh(w.f, p) : level[id] ?? 0),
        side, runs: runs(w.f) });
    });
    /* За общий остаток борются только те входы, которые его ТРАТЯТ. Вход,
       который не расходует, ни у кого ничего не отнимает: он ограничен
       сам по себе — тем, чего эта функция ещё не обрабатывала. */
    const demand = {};
    wave.forEach(({ f, n, takes }) => takes.filter(portSpends).forEach((p) => {
      demand[p.trait] = (demand[p.trait] || 0)
        + portQty(p, { kind: "takes", side, runs: runs(f) }) * n;
    }));
    const share = {};
    Object.keys(demand).forEach((id) => {
      const have = level[id] ?? 0;
      share[id] = demand[id] > have ? (have > 0 ? have / demand[id] : 0) : 1;
    });
    // Своя доля у входа, который не расходует: сколько его выполнений
    // вообще обеспечено новым, ещё не обработанным.
    const mine = (f, p, n) => {
      const need = portQty(p, { kind: "takes", side, runs: runs(f) }) * n;
      if (!(need > 0)) return 1;
      return Math.min(1, fresh(f, p) / need);
    };
    // Функцию держит самый дефицитный её вход: наполовину сделанной работы
    // не бывает, но половина выполнений за месяц — бывает.
    wave.forEach((w) => {
      w.k = w.takes.reduce((k, p) => Math.min(k,
        portSpends(p) ? (share[p.trait] ?? 1) : mine(w.f, p, w.n)), 1);
      /* Фактор ЖДЁТ. Он заранее знает, сколько ему нужно на одно
         срабатывание, и берёт только тогда, когда это количество появилось:
         на неполную порцию он не срабатывает, а ресурс копится до следующей
         попытки. Задача так не может — работу делят и делают частями, — а
         фактор либо случился целиком, либо не случился вовсе.

         Считаем по тому, что фактору и правда достанется: доля `share`
         учитывает, что за тот же ресурс борются другие. */
      if (isFactor(w.f) && w.n > 0) {
        const whole = w.takes.reduce((least, p) => {
          const need = portQty(p, { kind: "takes", side, runs: runs(w.f) });
          if (!(need > 0)) return least;
          const got = portSpends(p)
            ? (level[p.trait] ?? 0) * (share[p.trait] ?? 1)
            : fresh(w.f, p);
          return Math.min(least, Math.floor(got / need));
        }, Infinity);
        w.k = whole === Infinity ? 1 : Math.max(0, Math.min(w.k, whole / w.n));
      }
    });

    wave.forEach(({ f, n, k, takes }) => {
      takes.forEach((p) => {
        if (level[p.trait] == null) return;
        const q = portQty(p, { kind: "takes", side, runs: runs(f) }) * n * k;
        // Расходует — взятое исчезает у всех. Не расходует — остаётся на
        // месте, но этой функцией уже обработано.
        if (portSpends(p)) level[p.trait] -= q;
        else seen[seenKey(f, p)] = (seen[seenKey(f, p)] || 0) + q;
      });
      f.gives.forEach((g) => {
        if (level[g.trait] == null) return;
        level[g.trait] += portQty(g, { kind: "gives", side, runs: runs(f) }) * n * k;
      });
    });

    traits.forEach((t) => {
      // Ресурс не уходит в минус: взять больше, чем есть, нельзя — и то,
      // чего нет, не должно тянуть график под ноль.
      level[t.id] = Math.max(0, level[t.id]);
      out[t.id].push(level[t.id]);
    });
    /* Обработанного не бывает больше, чем есть вообще: единицы, которые
       эта функция когда-то обработала, могла израсходовать соседняя — и
       тогда они не должны навсегда закрывать ей дорогу. */
    Object.keys(seen).forEach((k) => {
      const id = k.slice(k.indexOf("|") + 1);
      seen[k] = Math.min(seen[k], level[id] ?? 0);
    });
  }
  return out;
}

/**
 * Полный прогноз: лента гипотезы и линия факта.
 *
 * Линия факта появляется только тогда, когда хоть одна функция и правда
 * выполнялась. Без выполнений её нет вовсе — иначе план показался бы
 * измерением.
 */
export function forecast(model, { span = 24, runsOf, plan, seed = 1 } = {}) {
  const anyFact = (model.funcs || []).some((f) => hasFact(runsOf ? runsOf(f.id) : []));
  return {
    lo: runSide(model, { span, side: "lo", runsOf, plan, seed }),
    hi: runSide(model, { span, side: "hi", runsOf, plan, seed }),
    fact: anyFact ? runSide(model, { span, side: "fact", runsOf, plan, seed }) : null,
    span,
  };
}

/**
 * На каком месяце прогноза ресурс дорастает до нужного уровня.
 *
 * Уровень приходит извне — из цели, а не из самого ресурса: у ресурса
 * своего «сколько нужно» больше нет, потому что цель это не число, а
 * намерение со сроком, темпом и ценой (см. `lib/goals.js`).
 *
 * Два ответа, а не один: «в лучшем случае» — по верхней границе, «наверняка»
 * — по нижней. Одна дата здесь была бы обещанием, которого вилка не даёт.
 */
export function reach(fc, traitId, want) {
  if (want == null || !(want > 0)) return null;
  const first = (row) => {
    if (!row) return null;
    const at = row.findIndex((v) => v >= want);
    return at < 0 ? null : at;
  };
  return { best: first(fc.hi?.[traitId]), sure: first(fc.lo?.[traitId]),
    fact: first(fc.fact?.[traitId]) };
}

/**
 * Что актив за месяц отдаёт и получает.
 *
 * Передача — это выход функции ресурсом чужого актива: ресурс уходит
 * туда, где он есть. Здесь она превращается в числа: сколько ресурса в
 * месяц уезжает из актива и сколько приезжает. Отдельного получателя у
 * выхода нет — его называет сам ресурс.
 */
export function transfers(model, { runsOf, plan } = {}) {
  const { funcs = [], traits = [] } = model;
  const at = (id) => traits.find((t) => t.id === id);
  const out = [];
  funcs.forEach((f) => {
    const rs = runsOf ? runsOf(f.id) : [];
    // Столько же выполнений, сколько в прогнозе: стрелка обязана говорить о
    // том же будущем, что и график, иначе они спорят друг с другом.
    const cap = cycles(f, rs);
    const n = plan
      ? Math.min(cap, (plan.perMonth?.[f.id] || 0) + (plan.once?.[f.id] || 0)) : cap;
    /* Стрелка рисуется всегда, даже когда ничего не запланировано: она
       говорит о СТРОЕНИИ — эта функция отдаёт ресурс в тот актив, — а числа
       на ней уже про планы. Убрать её вместе с числами значило бы спрятать
       связь, которая никуда не делась. */
    f.gives.forEach((g) => {
      const to = at(g.trait)?.e;
      if (!to || to === f.e) return;
      out.push({
        id: `${f.id}-${g.id}`,
        func: f.id,
        from: f.e,
        to,
        trait: g.trait,
        name: at(g.trait)?.l || "",
        lo: portQty(g, { kind: "gives", side: "lo", runs: rs }) * n,
        hi: portQty(g, { kind: "gives", side: "hi", runs: rs }) * n,
      });
    });
  });
  return out;
}

/**
 * Нагрузка человека: сколько часов в месяц на нём висит.
 *
 * Часы берутся из функций, где он исполнитель, и делятся поровну между
 * исполнителями: если функцию делают двое, каждому достаётся половина
 * выполнений. Это не измерение занятости, а следствие модели, — но оно
 * показывает, на кого свалено больше, чем на других.
 */
export function load(model, { runsOf, plan } = {}) {
  const by = {};
  (model.funcs || []).forEach((f) => {
    const rs = runsOf ? runsOf(f.id) : [];
    const hours = runHours(rs) ?? hoursOf(f);
    /* Столько выполнений, сколько требуют применённые цели, но не больше
       потолка. Без целей — потолок: это ответ на вопрос «сколько выйдет,
       если функция будет идти без остановки». */
    const cap = cycles(f, rs);
    const n = plan
      ? Math.min(cap, (plan.perMonth?.[f.id] || 0) + (plan.once?.[f.id] || 0)) : cap;
    // У фактора исполнителей нет; если они там остались от прежней правки,
    // считать их нагрузку всё равно нельзя — фактор происходит сам.
    /* Ноль выполнений — это «не назначено», а не «назначено ноль»: строка
       «0 ч» на человеке говорила бы, что работа есть, просто пустая. */
    if (isFactor(f) || !f.owners.length || !(hours > 0) || !(n > 0)) return;
    const each = (hours * n) / f.owners.length;
    f.owners.forEach((p) => { by[p] = (by[p] || 0) + each; });
  });
  return by;
}

/* ════════════════════════════════════════════════════════════════
   ЧТО НУЖНО СДЕЛАТЬ, ЧТОБЫ ДОЙТИ ДО ЦЕЛИ

   Прогноз отвечает на вопрос «куда система придёт сама». Здесь — обратный
   вопрос, и он владельцу нужнее: поставил цель на ресурсе — покажи, что для
   неё надо сделать и сколько это займёт.

   Считается разворачиванием от цели назад: чтобы получить ресурс, нужны
   выполнения функции, которая его выдаёт; на них уйдут её входы; чтобы
   взять входы, нужны выполнения тех функций, которые выдают уже их. То, что
   уже есть в остатках, идёт в дело первым — производить то, что и так лежит,
   незачем.

   ─── два времени, а не одно ───

   · «работы всего» — сумма часов по всем выполнениям: столько человеко-часов
     стоит цель;
   · «займёт» — календарный срок по самой длинной цепочке зависимостей:
     функции разных активов идут параллельно, а вот та, что ждёт чужой выход,
     раньше него не начнётся.

   Расписание считается здесь же: функция, которая делается час, но
   повторяется раз в месяц, даёт на цикл месяц, а не час.

   ─── чего расчёт не скрывает ───

   Если ресурс не выдаёт ни одна функция, он попадает в `missing`: цель
   недостижима, и молчать об этом нельзя — иначе план выглядел бы полным, а
   на деле в нём дыра. Если цепочка замкнулась сама на себя (ресурс нужен
   для того, чтобы получить ресурс), план обрывается и говорит об этом.
   ════════════════════════════════════════════════════════════════ */

/** Сколько ресурса функция выдаёт за одно выполнение. */
const givesOf = (f, trait, side, runs) => f.gives
  .filter((g) => g.trait === trait)
  .reduce((sum, g) => sum + portQty(g, { kind: "gives", side, runs }), 0);

/**
 * План под одну цель.
 *
 * @param side  "lo" — осторожно (выдают по минимуму, берут по максимуму),
 *              "hi" — щедро. Разница между ними и есть честная вилка плана.
 */
export function solve(model, { trait, want, side = "hi", runsOf, passes = 200,
  useStock = true } = {}) {
  const { traits = [], funcs = [] } = model;
  const runsFor = (f) => (runsOf ? runsOf(f.id) : []);
  const target = traits.find((t) => t.id === trait);
  const goal = num(want);
  const empty = { need: 0, spent: {}, held: {}, steps: [], workHours: 0, criticalHours: 0,
    missing: [], looped: false, ok: true };
  if (!target || !(goal > 0)) return empty;

  /* Остатки: то, что уже лежит, идёт в дело первым.

     `useStock: false` обнуляет остаток ТОЛЬКО у самой цели. Так считается
     цель с темпом: «один клиент в неделю» — это поток, и двадцать уже
     имеющихся клиентов не делают работу сделанной. А запасы входов при
     этом остаются: они настоящие, и тратятся они на самом деле. Обнулять
     заодно и их значило бы потребовать производить то, что приходит
     извне, — и тогда недостижимой оказалась бы любая цель. */
  const stock = {};
  traits.forEach((t) => {
    stock[t.id] = !useStock && t.id === trait ? 0 : num(t.have);
  });
  // Нехватка считается тем же остатком, что и тратится потом в цикле, —
  // иначе то, что уже есть, вычлось бы дважды, и план недосчитывал бы
  // ровно на текущее значение ресурса.
  const short = goal - Math.min(stock[trait] ?? 0, goal);

  if (short <= 1e-9) return { ...empty, need: 0 };

  const runsBy = {};                 // сколько выполнений какой функции
  const missing = new Set();
  const need = { [trait]: goal };
  /* Отдельная очередь для входов, которые НЕ расходуются. Их всё равно
     надо иметь: каждое выполнение обрабатывает свою единицу, и если её
     нет — её кто-то должен произвести. Но остаток они не тратят: то же
     самое достанется и другой функции, и обнулять им склад значило бы
     объявить нехваткой то, что лежит на месте.

     Очередь ведётся ПО ФУНКЦИЯМ: ограничение «второй раз не берём»
     принадлежит одной функции, и лежащие четыре единицы закрывают нужду
     каждой из двух, а не половину общей нужды в восьми. */
  const keep = {};                   // "функция|ресурс" → сколько надо иметь
  // Сколько чего понадобилось иметь, ничего не тратя.
  const held = {};
  // Во что цель обходится по ресурсам: сколько каждого понадобилось всего.
  // Считается здесь, а не после, потому что спрос набегает по кругам — то,
  // что нужно для входа, само требует входов.
  const spent = {};
  const producedFor = {};            // кто чей вход закрывал — для цепочки
  const chosen = {};                 // что функция взяла из групп «или»
  let looped = false;
  let guard = 0;

  const pick = (id) => {
    // Из нескольких производителей берём того, кто выдаёт больше за раз:
    // выбор должен быть один и тот же при каждом пересчёте, иначе план
    // прыгал бы от перерисовки к перерисовке.
    const able = funcs.filter((f) => givesOf(f, id, side, runsFor(f)) > 0);
    if (!able.length) return null;
    return able.reduce((best, f) => (
      givesOf(f, id, side, runsFor(f)) > givesOf(best, id, side, runsFor(best)) ? f : best));
  };

  while (guard < passes) {
    const spending = Object.keys(need).find((k) => need[k] > 1e-9);
    const holding = spending ? null : Object.keys(keep).find((k) => keep[k] > 1e-9);
    if (!spending && !holding) break;
    guard += 1;
    const holds = !spending;
    const id = holds ? holding.slice(holding.indexOf("|") + 1) : spending;
    const want4 = holds ? keep[holding] : need[spending];
    if (holds) { keep[holding] = 0; held[id] = Math.max(held[id] || 0, want4); }
    else { need[id] = 0; spent[id] = (spent[id] || 0) + want4; }

    // Сначала берём из остатка — производить то, что уже есть, незачем.
    // То, что не расходуется, остаток не уменьшает: оно там и останется.
    const fromStock = Math.min(stock[id] ?? 0, want4);
    if (!holds) stock[id] = (stock[id] ?? 0) - fromStock;
    const rest = want4 - fromStock;
    if (rest <= 1e-9) continue;

    const f = pick(id);
    if (!f) { missing.add(id); continue; }
    const use = takesOf(f, { have: (x) => stock[x] ?? 0, side, runs: runsFor(f) });
    chosen[f.id] = use;
    const per = givesOf(f, id, side, runsFor(f));
    // Выполнение целое: половины выполнения не бывает.
    const n = Math.ceil(rest / per);
    runsBy[f.id] = (runsBy[f.id] || 0) + n;
    (producedFor[id] = producedFor[id] || new Set()).add(f.id);
    /* Лишнее, что вышло сверх нужного, остаётся в остатке — оно не
       пропадает. А то, что нужно было только ИМЕТЬ, остаётся целиком:
       обработали и положили обратно. */
    stock[id] = (stock[id] ?? 0) + (holds ? n * per : n * per - rest);
    /* В группе «или» берётся то, чего хватает на дольше. Если пусто везде —
       первый по списку: порядок вариантов человек задал сам, и это его
       предпочтение, а не случайность. */
    use.forEach((p) => {
      const q = portQty(p, { kind: "takes", side, runs: runsFor(f) }) * n;
      if (!(q > 0)) return;
      if (portSpends(p)) need[p.trait] = (need[p.trait] || 0) + q;
      else keep[`${f.id}|${p.trait}`] = (keep[`${f.id}|${p.trait}`] || 0) + q;
    });
  }
  if (guard >= passes) looped = true;

  const steps = Object.entries(runsBy).map(([id, n]) => {
    const f = funcs.find((x) => x.id === id);
    // Сторона та же, что у всего плана: осторожная оценка считает по долгой
    // работе и редкой попытке, щедрая — по быстрой и частой.
    const step = stepHours(f, runsFor(f), side);
    /* Часы фактора — не человеко-часы: фактор происходит сам, и в бюджет
       человека его время не идёт. Календарный срок при этом остаётся —
       ждать его всё равно приходится. */
    const own = isFactor(f) ? 0 : (runHours(runsFor(f)) ?? hoursOf(f)) * n;
    return { func: id, name: f.name, e: f.e, runs: n, factor: isFactor(f),
      takes: chosen[id] || [], workHours: own, calendarHours: step * n };
  }).sort((a, b) => b.calendarHours - a.calendarHours);

  /* Календарный срок — по самой длинной цепочке: функция, ждущая чужой
     выход, раньше него не начнётся, а не связанные друг с другом идут
     параллельно. Повторный заход по кругу обрываем: цепочка, которая
     кормит сама себя, длины не имеет. */
  const byId = Object.fromEntries(steps.map((x) => [x.func, x]));
  /* `before` — когда функция может начаться: не раньше, чем созреет самый
     долгий из её входов. Это же число нужно и снаружи, чтобы разложить
     будущие задачи по календарю, поэтому оно ложится в шаг как
     `startHours`, а не остаётся внутри подсчёта критического пути. */
  const before = (id, seen = new Set()) => {
    const f = funcs.find((y) => y.id === id);
    if (!f || seen.has(id)) return 0;
    const next = new Set([...seen, id]);
    // Ждать надо только то, что функция и правда берёт: невыбранный вариант
    // группы «или» ей не нужен, и удлинять цепочку им не за что.
    return (chosen[id] || f.takes).reduce((m, p) => {
      const makers = [...(producedFor[p.trait] || [])];
      return Math.max(m, ...makers.map((mid) => chain(mid, next)), 0);
    }, 0);
  };
  const chain = (id, seen = new Set()) => {
    const x = byId[id];
    if (!x || seen.has(id)) return 0;
    return x.calendarHours + before(id, seen);
  };
  steps.forEach((x) => { x.startHours = before(x.func); });

  return {
    need: short,
    spent,
    held,
    steps,
    workHours: steps.reduce((s, x) => s + x.workHours, 0),
    criticalHours: Math.max(0, ...steps.map((x) => chain(x.func))),
    missing: [...missing],
    looped,
    ok: !missing.size && !looped && steps.length > 0,
  };
}

/**
 * План с обеих сторон вилки: осторожной и щедрой.
 *
 * Одно число здесь было бы обещанием: сколько выполнений понадобится,
 * зависит от того, по нижней границе выйдет выход функции или по верхней.
 */
export function solveRange(model, { trait, want, runsOf, useStock = true } = {}) {
  return {
    lo: solve(model, { trait, want, side: "lo", runsOf, useStock }),
    hi: solve(model, { trait, want, side: "hi", runsOf, useStock }),
  };
}


/**
 * Что план сделает с ресурсами: чего прибавится, чего убавится.
 *
 * Считается по тем же выполнениям, что и сам план: каждое берёт свои входы
 * и выдаёт свои выходы. Итог — ЧИСТОЕ изменение по каждому ресурсу: то, что
 * функция и производит, и потребляет, показывать двумя строками значило бы
 * пугать числами, которые друг друга гасят.
 */
export function effect(model, steps = [], { side = "hi", runsOf } = {}) {
  const funcs = model.funcs || [];
  const by = {};
  const add = (id, v) => { by[id] = (by[id] || 0) + v; };
  steps.forEach((st) => {
    const f = funcs.find((x) => x.id === st.func);
    if (!f) return;
    const runs = runsOf ? runsOf(f.id) : [];
    f.gives.forEach((g) => add(g.trait, portQty(g, { kind: "gives", side, runs }) * st.runs));
    /* Тратится только выбранный вариант группы «или», а не все сразу, — и
       только тот вход, который и правда расходуется: обработанное, но не
       израсходованное, никуда с полки не девается. */
    (st.takes || takesOf(f, { have: () => 0, side, runs }))
      .filter(portSpends)
      .forEach((p) => add(p.trait, -portQty(p, { kind: "takes", side, runs }) * st.runs));
  });
  return by;
}

/**
 * Когда какие выполнения придётся делать.
 *
 * Функция начинается не раньше, чем созреют её входы (`startHours`), а её
 * выполнения идут одно за другим. Ответ — список будущих задач с датами:
 * человек должен видеть, во что цель превратится на доске, ДО того как
 * нажмёт «применить», а не после.
 */
export function scheduleOf(steps = [], { from = Date.now() } = {}) {
  const rows = [];
  // Фактор происходит без человека — задачи по нему не заводятся.
  steps.filter((st) => !st.factor).forEach((st) => {
    const per = st.runs > 0 ? st.calendarHours / st.runs : 0;
    for (let i = 0; i < st.runs; i += 1) {
      const at = from + (st.startHours + per * i) * 3600000;
      rows.push({ func: st.func, name: st.name, e: st.e, no: i + 1, of: st.runs,
        start: new Date(at), end: new Date(at + per * 3600000) });
    }
  });
  return rows.sort((a, b) => a.start - b.start);
}

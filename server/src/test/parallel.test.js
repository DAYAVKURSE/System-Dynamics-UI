import { describe, expect, it } from "vitest";
import { snapshotOf } from "../lib/reportView.js";

/* ОДНОВРЕМЕННЫЕ ВЫПОЛНЕНИЯ — два разных предела, и снимок обязан считать
   их так же, как экран.

   «На воркера» — сколько дел держит один человек. «На актив» — сколько их
   идёт в активе вообще: станок один, кабинет один, лицензий три. Людей
   при этом не считаем (инвариант 6), поэтому в счёт идёт МЕНЬШИЙ из двух;
   пустой предел актива — «не ограничено», иначе прежние схемы схлопнулись
   бы в очередь. */

const model = (over = {}) => ({
  entities: [{ id: "e1", name: "Студия" }],
  traits: [{ id: "t1", e: "e1", l: "заявка" }, { id: "t2", e: "e1", l: "макет" }],
  funcs: [{ id: "f1", e: "e1", name: "Собрать макет", dur: 1, durHi: 1, durUnit: "дн",
    takes: [{ id: "p1", trait: "t1", lo: 1, hi: 1 }],
    gives: [{ id: "p2", trait: "t2", lo: 1, hi: 1 }], ...over }],
  tasks: [], materials: [], reports: [{ id: "rs1", name: "Макеты", trait: "t1", qty: 4 }],
});
const calendar = (over) => snapshotOf(model(over), "rs1").block.plan.calendarHours[1];

describe("два предела одновременности в снимке отчёта", () => {
  it("без настроек четыре выполнения идут очередью — четыре дня", () => {
    expect(calendar({})).toBe(4 * 24);
  });

  it("четыре на воркера — одна волна, один день", () => {
    expect(calendar({ par: 4 })).toBe(24);
  });

  it("предел актива прижимает: четверо под силу, а разом идут двое", () => {
    expect(calendar({ par: 4, parAll: 2 })).toBe(2 * 24);
  });

  it("пустой предел актива ничего не ограничивает", () => {
    expect(calendar({ par: 4, parAll: 0 })).toBe(24);
  });

  it("предел актива шире, чем под силу одному, — берётся меньший", () => {
    expect(calendar({ par: 2, parAll: 9 })).toBe(2 * 24);
  });
});

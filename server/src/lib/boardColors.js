/** Номер в палитре по id: FNV-1a — короткий, без криптографии, и один и
 *  тот же id всегда даёт одно и то же число. */
export function hashIndex(id, n) {
  let h = 0x811c9dc5;
  const s = String(id ?? "");
  for (let i = 0; i < s.length; i += 1) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return n > 0 ? h % n : 0;
}

const rgbOf = (hex) => {
  const h = String(hex || "").trim().replace(/^#/, "");
  const full = /^[0-9a-f]{3}$/i.test(h) ? h.split("").map((c) => c + c).join("") : h;
  if (!/^[0-9a-f]{6}$/i.test(full)) return null;
  return [0, 2, 4].map((i) => parseInt(full.slice(i, i + 2), 16));
};

/** Относительная яркость по WCAG 2.x. */
export function luminance(hex) {
  const rgb = rgbOf(hex);
  if (!rgb) return 0;
  const [r, g, b] = rgb.map((c) => {
    const s = c / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

const contrast = (a, b) => (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
const DARK_INK = "#111111";
const LIGHT_INK = "#FFFFFF";

/**
 * Чем писать по этому цвету: почти чёрным или белым — что контрастнее по
 * WCAG (владелец: «сами буквы чёрными или белыми, должно быть
 * автоматически подобрано для контраста с этим цветом»). Та же функция
 * живёт в web/src/boardColors.js — расходиться им нельзя.
 */
export function inkOn(hex) {
  if (!rgbOf(hex)) return LIGHT_INK;
  const l = luminance(hex);
  return contrast(l, luminance(DARK_INK)) >= contrast(l, luminance(LIGHT_INK)) ? DARK_INK : LIGHT_INK;
}

/* ─────── когда палитра кончилась ─────── */

const lin = (c) => {
  const v = c / 255;
  return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
};
const gam = (v) => {
  const s = v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055;
  return Math.round(Math.max(0, Math.min(1, s)) * 255);
};
const WHITE = [0.95047, 1, 1.08883];
const labF = (t) => (t > 216 / 24389 ? Math.cbrt(t) : (24389 / 27 * t + 16) / 116);
const labFi = (t) => (t ** 3 > 216 / 24389 ? t ** 3 : (116 * t - 16) / (24389 / 27));

/** Цвет в CIE Lab (D65) — пространство, где расстояние близко к видимой разнице. */
export function labOf(hex) {
  const rgb = rgbOf(hex);
  if (!rgb) return null;
  const [r, g, b] = rgb.map(lin);
  const xyz = [0.4124 * r + 0.3576 * g + 0.1805 * b, 0.2126 * r + 0.7152 * g + 0.0722 * b,
    0.0193 * r + 0.1192 * g + 0.9505 * b];
  const [fx, fy, fz] = xyz.map((v, i) => labF(v / WHITE[i]));
  return [116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)];
}

/** Разница двух цветов на глаз — ΔE CIE76; негодный цвет — бесконечно далеко. */
export function deltaE(a, b) {
  const x = Array.isArray(a) ? a : labOf(a);
  const y = Array.isArray(b) ? b : labOf(b);
  if (!x || !y) return Infinity;
  return Math.hypot(x[0] - y[0], x[1] - y[1], x[2] - y[2]);
}

/** Светлота, насыщенность, оттенок (LCh) → «#RRGGBB»; вне охвата sRGB — к краю. */
function hexOfLch(L, C, h) {
  const a = C * Math.cos((h * Math.PI) / 180);
  const b = C * Math.sin((h * Math.PI) / 180);
  const fy = (L + 16) / 116;
  const [X, Y, Z] = [fy + a / 500, fy, fy - b / 200].map((f, i) => WHITE[i] * labFi(f));
  const rgb = [3.2406 * X - 1.5372 * Y - 0.4986 * Z, -0.9689 * X + 1.8758 * Y + 0.0415 * Z,
    0.0557 * X - 0.204 * Y + 1.057 * Z];
  return `#${rgb.map((v) => gam(v).toString(16).padStart(2, "0")).join("").toUpperCase()}`;
}

/** На глаз различимы — не ближе этого (ΔE CIE76). */
export const MIN_DELTA_E = 8;
const GOLDEN_ANGLE = 137.508;
const TRIES = 120;

/* Фон доски, который палитра не дала, — не светлее самого светлого фона
   палитры: тогда любой цвет участника на нём держит свои 3:1. Ступени
   светлоты и насыщенности — от палитры к ещё более тёмным: место среди
   тёмных цветов, различимых на глаз, кончается быстро. */
const BOARD_Y_MAX = Math.max(...BOARD_COLORS.map(luminance));
const BOARD_STEPS = [[13.5, 20], [15, 14], [11, 20], [12, 14], [15.5, 6], [11.5, 6], [9, 16],
  [9, 10], [7, 14], [7, 6], [5, 12]];
/* Цвет участника сверх палитры: буквы на нём — не меньше 4,5:1, к самому
   светлому фону доски — не меньше 3:1 (к остальным, значит, тоже). */
const MEMBER_STEPS = [[66, 42], [58, 38], [74, 34], [62, 26]];
const memberFits = (hex) => {
  const l = luminance(hex);
  return contrast(l, luminance(inkOn(hex))) >= 4.5 && contrast(l, BOARD_Y_MAX) >= 3;
};
const boardFits = (hex) => luminance(hex) <= BOARD_Y_MAX;

/**
 * Достроить цвет, которого нет среди занятых: светлота и насыщенность — по
 * ступеням (сперва светлее и сочнее, потом темнее), оттенок на каждой
 * ступени шагает по «золотому углу» (так соседние шаги ложатся в разные
 * края круга). Первый, кто отстоит от всех занятых
 * хотя бы на MIN_DELTA_E и подходит по контрасту, — он. Такого нет
 * (занято уже очень много) — самый далёкий от занятых: ближе, чем хотелось
 * бы, но всё равно свой, а не чужой повтор. Начало круга — по хэшу id:
 * тот же id при тех же занятых получает тот же цвет.
 */
function freshColor(steps, fits, taken, id) {
  const used = taken.map(labOf).filter(Boolean);
  const start = hashIndex(id, 360);
  let best = null;
  let bestD = -1;
  for (const [L, C] of steps) {
    for (let k = 0; k < TRIES; k += 1) {
      const hex = hexOfLch(L, C, (start + k * GOLDEN_ANGLE) % 360);
      if (!fits(hex)) continue;
      const lab = labOf(hex);
      // Ближайший из занятых; ближе лучшего найденного — дальше не считать:
      // лучшим он уже не станет (и до MIN_DELTA_E, раз лучший до неё не дотянул).
      let d = Infinity;
      for (const u of used) {
        d = Math.min(d, deltaE(u, lab));
        if (d <= bestD) break;
      }
      if (d >= MIN_DELTA_E) return hex;
      if (d > bestD) { bestD = d; best = hex; }
    }
  }
  return best;
}

/**
 * Первый цвет палитры, которого нет среди занятых. Палитра кончилась —
 * достроенный (freshColor), а не повтор занятого: «свой цвет» у каждого
 * участника и «разные цвета» у досок держатся и за краем палитры.
 */
export function pickColor(palette, taken, id) {
  const list = (taken || []).map((c) => String(c || "").toUpperCase());
  const used = new Set(list);
  const free = palette.find((c) => !used.has(c.toUpperCase()));
  if (free) return free;
  const fresh = palette === BOARD_COLORS ? freshColor(BOARD_STEPS, boardFits, list, id)
    : palette === MEMBER_COLORS ? freshColor(MEMBER_STEPS, memberFits, list, id) : null;
  return fresh || palette[hashIndex(id, palette.length)];
}

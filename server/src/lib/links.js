/* ════════════════════════════════════════════════════════════════
   ССЫЛКА НА ЗВОНОК

   Звонок — ОТДЕЛЬНАЯ страница (/call) со своим бандлом: ни вкладки
   модели, ни самой модели в нём нет. Ссылка из приглашения обязана
   открывать именно её, и открываться она должна у любого, кому попала, —
   без всякой регистрации в боте.

   Открыть эту страницу мини-приложением Telegram умеет двумя способами,
   и они НЕ равноценны по высоте окна:

   · t.me/<бот>/<короткое имя>?startapp=call_… — отдельное приложение,
     заведённое в @BotFather через /newapp. Короткое имя лежит в
     TELEGRAM_CALL_APP (секрет репозитория либо команда «/callapp»).
     Работает в любом чате и у того, кто бота ни разу не открывал.
     НО: на весь экран и никак иначе — см. ниже.

   · t.me/<бот>?startapp=call_…&mode=compact — ГЛАВНОЕ мини-приложение
     бота, если владелец завёл его на тот же адрес https://<домен>/call
     (@BotFather → Bot Settings → Configure Mini App). Тогда «главное»
     приложение бота — это и есть окно звонка, модель по-прежнему живёт
     на кнопке меню и никак не задета. Включается командой «/callmain on»,
     которая сперва спрашивает у Telegram (getMe → has_main_web_app),
     заведено ли оно вообще: иначе такая ссылка молча превращается в
     ссылку на чат с ботом, и по ней не открывается ничего.

   · Ни того, ни другого нет — ссылка ведёт прямо на страницу,
     https://<домен>/call?call=…. Она тоже открывается у всех, но обычной
     страницей: камеру и микрофон Telegram надёжно даёт только
     мини-приложению, поэтому это запасной путь, а не равноценный.

   ─── почему пол-экрана требует именно главного приложения ───

   Документация обещает пол-экрана обоим: «Starting from Bot API 7.6, by
   default, Mini Apps of this type open to full-screen height… you can
   change this behavior by including the parameter mode=compact»
   (core.telegram.org/bots/webapps, раздел Direct Link Mini Apps).
   На деле клиенты ведут себя иначе, и это проверено по их исходникам:

   · Telegram Desktop разбирает mode, но compact выставляет ТОЛЬКО для
     ссылки на главное приложение: в local_url_handlers.cpp условие
     начинается с `appname.isEmpty()`, а у ссылки вида t.me/бот/имя имя
     не пустое. В requestApp() флага f_compact нет вовсе — он есть лишь
     в requestMain(). То есть для отдельного приложения mode=compact на
     десктопе не делает ничего, и никакая правка ссылки этого не изменит.

   · Android и iOS высоту берут из ответа сервера (webViewResultUrl.
     fullsize), а не из своего же намерения: в BotWebViewSheet.isFullSize()
     локальное значение перезаписано ответом. Отсюда открытая до сих пор
     ошибка bugs.telegram.org/c/45743 («no difference between compact and
     fullsize mode») и незакрытый PR DrKLO/Telegram#1930. Зато ответ
     сервера слушается — а им управляет настройка главного приложения в
     @BotFather. Поэтому путь через главное приложение — единственный, у
     которого есть шанс дать пол-экрана и на телефоне.

   Свернуть окно из самой страницы нельзя: expand() односторонний, метода
   «свернуть» в Mini Apps нет. Высота решается один раз, при открытии, —
   отсюда и вся возня со ссылкой.

   Про startapp: Telegram разрешает в нём только буквы, цифры, «_» и «-»
   (до 64 знаков). Наши id встреч именно такие (base64url), но если id
   вдруг окажется другим, ссылка уходит на страницу звонка, а не битым
   параметром, который Telegram отбросит молча.
   ════════════════════════════════════════════════════════════════ */

/** Годится ли id для параметра startapp — по правилам Telegram. */
export const startParamOk = (id) => /^[A-Za-z0-9_-]{1,58}$/.test(String(id));

/** Прямой адрес страницы звонка — без Telegram, для кого угодно. */
export const callPageLink = ({ publicUrl = "" } = {}, callId) =>
  `${publicUrl}/call?call=${encodeURIComponent(String(callId))}`;

export function callLinkFor(
  { botName = "", callApp = "", callMain = false, publicUrl = "" } = {}, callId,
) {
  const id = String(callId);
  if (!botName || !startParamOk(id)) return callPageLink({ publicUrl }, id);
  // Главное приложение — первым: только оно открывается на пол-экрана.
  if (callMain) return `https://t.me/${botName}?startapp=call_${id}&mode=compact`;
  if (!callApp) return callPageLink({ publicUrl }, id);
  return `https://t.me/${botName}/${callApp}?startapp=call_${id}&mode=compact`;
}

/** Ведёт ли ссылка в мини-приложение (а не на обычную страницу). */
export const isAppLink = (link) => String(link || "").startsWith("https://t.me/");

/**
 * Ссылка на ГЛАВНОЕ приложение бота: t.me/<бот>?startapp=…
 *
 * Отличается от ссылки на отдельное приложение (t.me/<бот>/<имя>?startapp=…)
 * ровно одним — отсутствием имени приложения. Различать их приходится
 * потому, что на пол-экрана открывается только первая.
 */
export const isMainAppLink = (link) => /^https:\/\/t\.me\/[^/?#]+\?/.test(String(link || ""));

/** Из окружения сервера. */
export const callLinkEnv = (env = process.env, botName = "") => ({
  botName,
  callApp: (env.TELEGRAM_CALL_APP || "").trim(),
  // Ровно «1»: пустая строка и любое другое значение — выключено. Так
  // настройка не включается сама собой от случайного мусора в .env.
  callMain: (env.TELEGRAM_CALL_MAIN || "").trim() === "1",
  publicUrl: (env.PUBLIC_URL || "").replace(/\/+$/, ""),
});

/** Короткое имя приложения звонка: то, что @BotFather разрешает в /newapp. */
export const callAppNameOk = (name) => /^[A-Za-z0-9_]{3,32}$/.test(String(name || ""));


/* ════════════════════════════════════════════════════════════════
   ССЫЛКА НА ЗВОНОК

   Звонок — ОТДЕЛЬНОЕ мини-приложение, а не вкладка модели и не сама
   модель: у него свой адрес (/call), свой бандл и своё окно. Ссылка из
   приглашения обязана открывать именно его, и открываться она должна у
   любого, кому попала, — без всякой регистрации в боте.

   Из этого следует, как ссылка собирается:

   · t.me/<бот>/<короткое имя>?startapp=call_…  — то самое отдельное
     мини-приложение. Заводится один раз в @BotFather (/newapp) с адресом
     https://<домен>/call; короткое имя хранится в TELEGRAM_CALL_APP —
     туда его кладёт либо секрет репозитория, либо команда «/callapp» в
     чате с ботом. Такая ссылка работает в любом чате и у человека,
     который бота ни разу не открывал (Telegram спросит подтверждение при
     первом запуске — и всё).

   · Нет короткого имени — ссылка ведёт прямо на страницу звонка,
     https://<домен>/call?call=…. Она тоже открывается у всех, но обычной
     страницей: камеру и микрофон Telegram надёжно даёт только
     мини-приложению, поэтому это запасной путь, а не равноценный.

   Чего здесь БОЛЬШЕ НЕТ и не должно появиться — ссылки на главное
   мини-приложение (t.me/<бот>?startapp=… или t.me/<бот>/<имя модели>).
   Во-первых, владелец просил обратного: звонок не должен открываться
   внутри приложения модели. Во-вторых, ссылка на главное приложение
   молча превращается в ссылку на чат с ботом, если оно не заведено в
   @BotFather, — то есть по ней не открывается ничего.

   mode=compact — окно открывается на пол-экрана; на весь экран человек
   тянет его сам.

   Про startapp: Telegram разрешает в нём только буквы, цифры, «_» и «-»
   (до 64 знаков). Наши id встреч именно такие (base64url), но если id
   вдруг окажется другим, ссылка уходит на страницу звонка, а не битым
   параметром, который Telegram отбросит молча.
   ════════════════════════════════════════════════════════════════ */

/** Годится ли id для параметра startapp — по правилам Telegram. */
export const startParamOk = (id) => /^[A-Za-z0-9_-]{1,58}$/.test(String(id));

/** Прямой адрес страницы звонка — без Telegram, для кого угодно. */
export const callPageLink = ({ publicUrl = "" } = {}, callId) =>
  `${publicUrl}/call?call=${encodeURIComponent(String(callId))}`;

export function callLinkFor({ botName = "", callApp = "", publicUrl = "" } = {}, callId) {
  const id = String(callId);
  if (!botName || !callApp || !startParamOk(id)) return callPageLink({ publicUrl }, id);
  return `https://t.me/${botName}/${callApp}?startapp=call_${id}&mode=compact`;
}

/** Из окружения сервера. */
export const callLinkEnv = (env = process.env, botName = "") => ({
  botName,
  callApp: (env.TELEGRAM_CALL_APP || "").trim(),
  publicUrl: (env.PUBLIC_URL || "").replace(/\/+$/, ""),
});

/** Короткое имя приложения звонка: то, что @BotFather разрешает в /newapp. */
export const callAppNameOk = (name) => /^[A-Za-z0-9_]{3,32}$/.test(String(name || ""));

